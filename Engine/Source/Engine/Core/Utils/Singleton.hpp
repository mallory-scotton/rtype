#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <memory>
#include <mutex>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief
///
///////////////////////////////////////////////////////////////////////////////
class Instantiable
{
protected:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    Instantiable(void) = default;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Remove copy constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    Instantiable(const Instantiable&) = delete;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~Instantiable() = default;

protected:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Remove copy assignment operator
    ///
    ///////////////////////////////////////////////////////////////////////////
    Instantiable& operator=(const Instantiable&) = delete;
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Singleton class template
///
/// \tparam T The type of the singleton class
///
///////////////////////////////////////////////////////////////////////////////
template <typename T>
class TSingleton : public Instantiable
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    static std::unique_ptr<T> m_instance;   //<! Singleton instance
    static std::once_flag m_onceFlag;       //<! Flag for thread-safe init

protected:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    TSingleton(void) = default;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~TSingleton() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the singleton instance
    ///
    /// \return Reference to the singleton instance
    ///
    ///////////////////////////////////////////////////////////////////////////
    static T& GetInstance(void)
    {
        std::call_once(
            m_onceFlag, []() { m_instance = std::make_unique<T>(); }
        );
        return *m_instance;
    }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the singleton instance with constructor arguments
    ///
    /// \tparam Args Variadic template parameter pack for constructor arguments
    /// \param args Arguments to forward to the constructor
    /// \return Reference to the singleton instance
    ///
    /// \note This will only use the arguments on first creation. Subsequent
    /// calls will ignore the arguments and return the existing instance.
    ///
    ///////////////////////////////////////////////////////////////////////////
    template <typename... Args>
    static T& GetInstance(Args&&... args)
    {
        std::call_once(
            m_onceFlag,
            [&args...]()
            { m_instance = std::make_unique<T>(std::forward<Args>(args)...); }
        );
        return *m_instance;
    }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Create the singleton instance with constructor arguments
    ///
    /// \tparam Args Variadic template parameter pack for constructor arguments
    /// \param args Arguments to forward to the constructor
    /// \return Reference to the singleton instance
    ///
    /// \note This is an alias for GetInstance with arguments for clarity
    ///
    ///////////////////////////////////////////////////////////////////////////
    template <typename... Args>
    static T& CreateInstance(Args&&... args)
    {
        return GetInstance(std::forward<Args>(args)...);
    }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the singleton instance exists
    ///
    /// \return true if instance exists, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    static Bool HasInstance(void) { return m_instance != nullptr; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Destroy the singleton instance
    ///
    /// \note This allows for controlled cleanup and recreation
    ///
    ///////////////////////////////////////////////////////////////////////////
    static void DestroyInstance(void)
    {
        m_instance.reset();
        // Reset the once_flag by reconstructing it
        new (&m_onceFlag) std::once_flag();
    }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get raw pointer to instance (can be null)
    ///
    /// \return Raw pointer to instance or nullptr if not created
    ///
    ///////////////////////////////////////////////////////////////////////////
    static T* GetInstancePtr(void) { return m_instance.get(); }
};

///////////////////////////////////////////////////////////////////////////////
// Static member definitions (must be in header for templates)
///////////////////////////////////////////////////////////////////////////////
template <typename T>
std::unique_ptr<T> TSingleton<T>::m_instance = nullptr;

template <typename T>
std::once_flag TSingleton<T>::m_onceFlag;

}   // namespace tkd
