///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief
///
///////////////////////////////////////////////////////////////////////////////
enum class EArchiveMode : UInt8
{
    None = 0,   //<! No mode
    Loading,    //<! Loading mode
    Saving      //<! Saving mode
};

///////////////////////////////////////////////////////////////////////////////
/// \brief
///
///////////////////////////////////////////////////////////////////////////////
class FArchive
{
protected:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    std::vector<UInt8> m_data;   //<! Data buffer for the archive
    Int32 m_version;             //<! Version of the archive
    EArchiveMode m_mode;         //<! Mode of the archive
    bool m_allowSeek;            //<! True if seeking is allowed
    SizeT m_position;            //<! Current position in the archive

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor.
    ///
    /// \param mode The mode of the archive (default is None).
    /// \param allowSeek True if seeking is allowed (default is true).
    ///
    ///////////////////////////////////////////////////////////////////////////
    FArchive(EArchiveMode mode = EArchiveMode::None, bool allowSeek = true);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Virtual destructor.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~FArchive() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Overloaded operator to serialize/deserialize a FString object.
    ///
    /// \param value Reference to the FString object to be
    /// serialized/deserialized.
    ///
    /// \return Reference to the current FArchive object.
    ///
    ///////////////////////////////////////////////////////////////////////////
    FArchive& operator<<(FString& value);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Overloaded operator to serialize/deserialize a std::string
    /// object.
    ///
    /// \param value Reference to the std::string object to be
    /// serialized/deserialized.
    ///
    /// \return Reference to the current FArchive object.
    ///
    ///////////////////////////////////////////////////////////////////////////
    FArchive& operator<<(std::string& value);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Template function to serialize/deserialize trivially copyable
    /// types.
    ///
    /// \tparam T Type of the value to serialize/deserialize.
    ///
    /// \param value Reference to the value to serialize/deserialize.
    ///
    /// \return Reference to the current FArchive object.
    ///
    ///////////////////////////////////////////////////////////////////////////
    template <typename T>
    FArchive& operator<<(T& value)
    {
        static_assert(
            std::is_trivially_copyable_v<T>,
            "FArchive can only serialize trivially copyable types"
        );
        Serialize(&value, sizeof(T));
        return *this;
    }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Serialize a block of data.
    ///
    /// \param data Pointer to the data block to serialize.
    /// \param size Size of the data
    ///
    /// \throws std::runtime_error if attempting to read past the end of the
    /// archive buffer in loading mode.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Serialize(void* data, SizeT size);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Template function to serialize trivially copyable types.
    ///
    /// \tparam T Type of the value to serialize.
    ///
    /// \param value Pointer to the value to serialize.
    /// \param length Number of elements to serialize (default is 1).
    ///
    ///////////////////////////////////////////////////////////////////////////
    template <typename T>
    typename std::enable_if_t<std::is_trivially_copyable_v<T>, void>
        Serialize(T* value, SizeT length = 1)
    {
        Serialize(static_cast<void*>(value), sizeof(T) * length);
    }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current position in the archive.
    ///
    /// \return Current position in the archive.
    ///
    ///////////////////////////////////////////////////////////////////////////
    SizeT Tell(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the current position in the archive.
    ///
    /// \param position New position to set in the archive.
    ///
    /// \throws std::runtime_error if seeking is not allowed
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Seek(SizeT position);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the total size of the archive data.
    ///
    /// \return Total size of the archive data.
    ///
    ///////////////////////////////////////////////////////////////////////////
    SizeT TotalSize(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get version of the archive.
    ///
    /// \return Version of the archive.
    ///
    ///////////////////////////////////////////////////////////////////////////
    Int32 GetVersion(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set version of the archive.
    ///
    /// \param version New version to set for the archive.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetVersion(Int32 version);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the mode of the archive.
    ///
    /// \return Mode of the archive.
    ///
    ///////////////////////////////////////////////////////////////////////////
    EArchiveMode GetMode(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the data buffer of the archive.
    ///
    /// \return Data buffer of the archive.
    ///
    ///////////////////////////////////////////////////////////////////////////
    const std::vector<UInt8>& GetData(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the data buffer of the archive.
    ///
    /// \param data New data buffer to set for the archive.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetData(const std::vector<UInt8>& data);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the data buffer of the archive by moving the provided data.
    ///
    /// \param data New data buffer to set for the archive (moved).
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetData(std::vector<UInt8>&& data);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Clear the archive data and reset position.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Clear(void);
};

}   // namespace tkd
