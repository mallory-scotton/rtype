#include <Engine/Core/Archives/FSaveArchive.hpp>
#include <Engine/Config.hpp>
#include <Engine/Core/Utils/FileSystem.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
FSaveArchive::FSaveArchive(const FilePath& filePath, Int32 version)
    : FArchive(EArchiveMode::Saving, true)
    , m_filePath(filePath)
{
    m_version = version;
}

///////////////////////////////////////////////////////////////////////////////
FSaveArchive::~FSaveArchive()
{
    if (m_data.size() > 0)
    {
        FileSystem::WriteBytesToFile(m_filePath, m_data);
    }
}

}   // namespace tkd
