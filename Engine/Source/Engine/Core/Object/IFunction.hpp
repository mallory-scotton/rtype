namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief RPC types for remote procedure calls
///
///////////////////////////////////////////////////////////////////////////////
enum class ERPCType : UInt8
{
    None,       //<! Not an RPC
    Server,     //<! Client->Server, requires validation
    Client,     //<! Server->Client
    Multicast   //<! Server->All Clients
};

///////////////////////////////////////////////////////////////////////////////
/// \brief IFunction class interface
///
///////////////////////////////////////////////////////////////////////////////
class IFunction
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~IFunction() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the function is bound
    ///
    /// \return True if the function is bound, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool IsBound(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the function name
    ///
    /// \return Function name
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual const FString& GetName(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the owner UObject of the function.
    ///
    /// \return The owner UObject of the function.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual const UObject& GetOwner(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the owner UObject of the function.
    ///
    /// \return The owner UObject of the function.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual UObject& GetOwner(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the RPC type
    ///
    /// \return RPC type
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ERPCType GetRPCType(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the RPC type
    ///
    /// \param type New RPC type
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetRPCType(ERPCType type) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Execute the function with the given parameters
    ///
    /// \param parameters Parameters to pass to the function
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void ExecuteSerialized(const std::vector<Byte>& parameters) = 0;
};

}   // namespace tkd
