///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Containers/FString.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
// Forward declaration
///////////////////////////////////////////////////////////////////////////////
class UObject;

///////////////////////////////////////////////////////////////////////////////
/// \brief Enumeration for property flags.
///
///////////////////////////////////////////////////////////////////////////////
enum class EPropertyFlags : UInt32
{
    None = 0,                //<! No flags
    EditAnywhere = 1 << 0,   //<! Property can be edited anywhere
    Replicated = 1 << 1,     //<! Property is replicated over the network
    ReadOnly = 1 << 2        //<! Property is read-only
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Interface for property classes.
///
///////////////////////////////////////////////////////////////////////////////
class IProperty
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Virtual destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~IProperty() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the name of the property.
    ///
    /// \return The name of the property.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual const FString& GetName(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the name of the property.
    ///
    /// \param name The new name for the property.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetName(const FString& name) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the owner UObject of the property.
    ///
    /// \return The owner UObject of the property.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual const UObject& GetOwner(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the owner UObject of the property.
    ///
    /// \return The owner UObject of the property.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual UObject& GetOwner(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the property path in the format "OwnerID/PropertyName".
    ///
    /// \return The property path as a FString.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FString GetPropertyPath(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Converts the property to a string representation.
    ///
    /// \return The string representation of the property.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FString ToString(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the value of the property.
    ///
    /// \param value The new value for the property.
    /// \param size The size of the value in bytes.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetValue(const void* value, SizeT size) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the flags associated with the property.
    ///
    /// \return The property flags.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual UInt32 GetFlags(void) const = 0;
};

}   // namespace tkd
