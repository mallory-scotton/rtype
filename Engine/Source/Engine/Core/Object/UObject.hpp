#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Containers/FString.hpp>
#include <string>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief UObject class definition.
///
/// This class represents a base object with a unique identifier and a name.
///
///////////////////////////////////////////////////////////////////////////////
class UObject
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Static Class Member
    ///////////////////////////////////////////////////////////////////////////
    static UInt64 s_nextObjectID;   //<! Static member to track the next
                                    // available object ID.

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    UInt64 m_objectID;   //<! Unique identifier for the object.
    FString m_name;      //<! Name of the object.

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief
    ///
    ///////////////////////////////////////////////////////////////////////////
    UObject(const FString& name = "<Unnamed>");

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Conversion operator to UInt64.
    ///
    ///////////////////////////////////////////////////////////////////////////
    operator UInt64(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Conversion operator to FString.
    ///
    ///////////////////////////////////////////////////////////////////////////
    operator FString(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Conversion operator to std::string.
    ///
    ///////////////////////////////////////////////////////////////////////////
    operator std::string(void) const;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the unique object ID.
    ///
    /// \return The unique object ID.
    ///
    ///////////////////////////////////////////////////////////////////////////
    UInt64 GetObjectID(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the name of the object.
    ///
    /// \return The name of the object.
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FString& GetName(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the name of the object.
    ///
    /// \param name The new name for the object.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetName(const FString& name);
};

}   // namespace tkd
