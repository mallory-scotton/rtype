///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Core/Object/UProperty.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
UProperty::UProperty(
    const FString& name,
    const std::type_index& type,
    SizeT offset,
    EPropertyFlags flags
)
    : m_name(name)
    , m_type(type)
    , m_offset(offset)
    , m_flags(flags)
{}

///////////////////////////////////////////////////////////////////////////////
const FString& UProperty::GetName(void) const { return m_name; }

///////////////////////////////////////////////////////////////////////////////
const std::type_index& UProperty::GetType(void) const { return m_type; }

///////////////////////////////////////////////////////////////////////////////
SizeT UProperty::GetOffset(void) const { return m_offset; }

}   // namespace tkd
