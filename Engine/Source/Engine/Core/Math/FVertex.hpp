#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math/FColor.hpp>
#include <Engine/Core/Math/Forward.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief
///
///////////////////////////////////////////////////////////////////////////////
class FVertex
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FVector3 position;   //<! Position of the vertex
    FColor color;        //<! The color of the vertex
    FVector3 uv;         //<! Texture coordinates of the vertex

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor, initializes position to (0,0,0), color to
    /// white, and uv to (0,0,0)
    ///
    ///////////////////////////////////////////////////////////////////////////
    FVertex(void);

    /////////////////////////////////////////////////////////////////////////////
    /// \brief Parameterized constructor to initialize vertex attributes
    ///
    /// \param position Position of the vertex
    /// \param color Color of the vertex
    /// \param uv Texture coordinates of the vertex
    ///
    ////////////////////////////////////////////////////////////////////////////
    FVertex(
        const FVector3& position,
        const FColor& color = FColor::White,
        const FVector3& uv = FVector3::Zero
    );
};

}   // namespace tkd
