#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math/FColor.hpp>
#include <Engine/Core/Math/Forward.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Vertex structure for rendering
///
///////////////////////////////////////////////////////////////////////////////
class FVertex
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FVector2f position;   //<! Position of the vertex
    FColor color;         //<! Color of the vertex
    FVector2f uv;         //<! Texture coordinates of the vertex

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor, initializes position to (0,0), color to
    /// white, and uv to (0,0)
    ///
    ///////////////////////////////////////////////////////////////////////////
    FVertex(void);

    /////////////////////////////////////////////////////////////////////////////
    /// \brief Parameterized constructor to initialize vertex attributes
    ///
    /// \param position Position of the vertex
    /// \param color Color of the vertex
    /// \param uv Texture coordinates of the vertex
    ///
    ////////////////////////////////////////////////////////////////////////////
    FVertex(
        const FVector2f& position,
        const FColor& color = FColor::White,
        const FVector2f& uv = FVector2f::Zero
    );
};

}   // namespace tkd
