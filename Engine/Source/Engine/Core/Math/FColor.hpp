#include <Engine/Config.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
// Pre-declaration of FLinearColor
///////////////////////////////////////////////////////////////////////////////
class FLinearColor;

///////////////////////////////////////////////////////////////////////////////
/// \brief Class representing a color with floating-point components
///
///////////////////////////////////////////////////////////////////////////////
class FColor
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    union
    {
        struct
        {
            Float32 r;   //<! Red component
            Float32 g;   //<! Green component
            Float32 b;   //<! Blue component
            Float32 a;   //<! Alpha component
        };

        Float32 data[4];   //<! Combined color value
    };

public:
    ///////////////////////////////////////////////////////////////////////////
    // Static Class Member
    ///////////////////////////////////////////////////////////////////////////
    static const FColor White;         //<! White color
    static const FColor Black;         //<! Black color
    static const FColor Red;           //<! Red color
    static const FColor Green;         //<! Green color
    static const FColor Blue;          //<! Blue color
    static const FColor Yellow;        //<! Yellow color
    static const FColor Cyan;          //<! Cyan color
    static const FColor Magenta;       //<! Magenta color
    static const FColor Transparent;   //<! Transparent color

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor, initializes color to black with full
    /// opacity
    ///
    ///////////////////////////////////////////////////////////////////////////
    FColor(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Parameterized constructor to initialize color components
    ///
    /// \param r Red component
    /// \param g Green component
    /// \param b Blue component
    /// \param a Alpha component
    ///
    ///////////////////////////////////////////////////////////////////////////
    FColor(Float32 r, Float32 g, Float32 b, Float32 a = 1.0f);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Conversion constructor from FLinearColor
    ///
    /// \param other The FLinearColor to convert
    ///
    ///////////////////////////////////////////////////////////////////////////
    FColor(const FLinearColor& other);

public:
    ////////////////////////////////////////////////////////////////////////////
    /// \brief Conversion operator to FLinearColor
    ///
    /// \return Converted FLinearColor object
    ///
    /////////////////////////////////////////////////////////////////////////////
    operator FLinearColor(void) const;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Converts this FColor to an FLinearColor
    ///
    /// \return Converted FLinearColor object
    ///
    ///////////////////////////////////////////////////////////////////////////
    FLinearColor ToLinearColor(void) const;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Creates an FColor from an FLinearColor
    ///
    /// \param other The FLinearColor to convert
    ///
    /// \return Converted FColor object
    ///
    ///////////////////////////////////////////////////////////////////////////
    static FColor FromLinearColor(const FLinearColor& other);
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Equality operator for FColor and FColor
///
/// \param lhs The FColor to compare
/// \param rhs The FColor to compare
///
/// \return True if the colors are equal, false otherwise
///
///////////////////////////////////////////////////////////////////////////////
bool operator==(const FColor& lhs, const FColor& rhs);

///////////////////////////////////////////////////////////////////////////////
/// \brief Inequality operator for FColor and FColor
///
/// \param lhs The FColor to compare
/// \param rhs The FColor to compare
///
/// \return True if the colors are not equal, false otherwise
///
///////////////////////////////////////////////////////////////////////////////
bool operator!=(const FColor& lhs, const FColor& rhs);

///////////////////////////////////////////////////////////////////////////////
/// \brief Equality operator for FColor and FLinearColor
///
/// \param lhs The FColor to compare
/// \param rhs The FLinearColor to compare
///
/// \return True if the colors are equal, false otherwise
///
///////////////////////////////////////////////////////////////////////////////
bool operator==(const FColor& lhs, const FLinearColor& rhs);

///////////////////////////////////////////////////////////////////////////////
/// \brief Inequality operator for FColor and FLinearColor
///
/// \param lhs The FColor to compare
/// \param rhs The FLinearColor to compare
///
/// \return True if the colors are not equal, false otherwise
///
///////////////////////////////////////////////////////////////////////////////
bool operator!=(const FColor& lhs, const FLinearColor& rhs);

}   // namespace tkd
