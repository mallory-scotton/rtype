///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <mutex>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Interface for a mutex abstraction
///
///////////////////////////////////////////////////////////////////////////////
class IMutex
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~IMutex() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Conversion operator to std::mutex&
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual operator std::mutex&() = 0;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Lock the mutex
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Lock(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Unlock the mutex
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Unlock(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Try to lock the mutex
    ///
    /// \return True if the mutex was successfully locked, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool TryLock(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the native std::mutex object
    ///
    /// \return Reference to the native std::mutex object
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual std::mutex& GetNativeMutex(void) = 0;
};

}   // namespace tkd
