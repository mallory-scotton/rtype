namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Enumeration for process status
///
///////////////////////////////////////////////////////////////////////////////
enum class EProcessStatus : UInt8
{
    Running = 0,    //<! Process is running
    Stopped = 1,    //<! Process is stopped
    Finished = 2,   //<! Process has finished
    Error = 3       //<! Process has encountered an error
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Abstract interface for process management
///
///////////////////////////////////////////////////////////////////////////////
class IProcess
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~IProcess() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Start the process
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Start(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Wait for the process to finish
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Wait(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the process is currently running
    ///
    /// \return True if the process is running, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool IsRunning(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current status of the process
    ///
    /// \return The current status of the process
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual int GetReturnValue(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the current process is the parent
    ///
    /// \return True if the current process is the parent, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool IsParent(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the current process is the child
    ///
    /// \return True if the current process is the child, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool IsChild(void) const = 0;
};

}   // namespace tkd
