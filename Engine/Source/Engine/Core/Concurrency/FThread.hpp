///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <atomic>
#include <Engine/Core/Concurrency/IThread.hpp>
#include <functional>
#include <stdexcept>
#include <thread>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Thread implementation using std::thread
///
///////////////////////////////////////////////////////////////////////////////
class FThread : public IThread
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Private class members
    ///////////////////////////////////////////////////////////////////////////
    std::thread m_thread;               //<! Underlying std::thread object
    std::function<void()> m_function;   //<! Function to execute in the thread
    bool m_started;   //<! true if the thread has been started

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor
    ///
    /// \param function Function to execute in the thread
    ///
    ///////////////////////////////////////////////////////////////////////////
    std::atomic<bool> running;   //<! true if the thread is running

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor
    ///
    /// \param function Function to execute in the thread
    ///
    ///////////////////////////////////////////////////////////////////////////
    explicit FThread(std::function<void()> function);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    ~FThread() override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Copy constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    FThread(const FThread&) = delete;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Move constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    FThread(FThread&&) = delete;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Copy assignment operator
    ///
    ///////////////////////////////////////////////////////////////////////////
    FThread& operator=(const FThread&) = delete;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Move assignment operator
    ///
    ///////////////////////////////////////////////////////////////////////////
    FThread& operator=(FThread&&) = delete;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Start the thread execution
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Start(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Wait for the thread to finish execution
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Join(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Detach the thread from the calling thread
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Detach(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the thread is joinable
    ///
    /// \return true if the thread is joinable, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool Joinable(void) const override;
};

}   // namespace tkd
