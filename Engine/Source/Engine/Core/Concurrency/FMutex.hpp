///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Core/Concurrency/IMutex.hpp>
#include <mutex>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Mutex implementation using std::mutex
///
///////////////////////////////////////////////////////////////////////////////
class FMutex : public IMutex
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Private class members
    ///////////////////////////////////////////////////////////////////////////
    std::mutex m_mutex;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor, initializes the mutex
    ///
    ///////////////////////////////////////////////////////////////////////////
    FMutex(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    ~FMutex() override = default;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Copy constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    FMutex(const FMutex&) = delete;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Move constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    FMutex(FMutex&&) = delete;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Copy assignment operator
    ///
    ///////////////////////////////////////////////////////////////////////////
    FMutex& operator=(const FMutex&) = delete;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Move assignment operator
    ///
    ///////////////////////////////////////////////////////////////////////////
    FMutex& operator=(FMutex&&) = delete;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Conversion operator to std::mutex&
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual operator std::mutex&() override;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Lock the mutex
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Lock(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Unlock the mutex
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Unlock(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Try to lock the mutex
    ///
    /// \return True if the mutex was successfully locked, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool TryLock(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the native std::mutex object
    ///
    /// \return Reference to the native std::mutex object
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual std::mutex& GetNativeMutex(void) override;
};

}   // namespace tkd
