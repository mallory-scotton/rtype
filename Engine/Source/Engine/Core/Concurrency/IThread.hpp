namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Interface for a thread abstraction
///
///////////////////////////////////////////////////////////////////////////////
class IThread
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~IThread() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Start the thread execution
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Start(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Wait for the thread to finish execution
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Join(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Detach the thread from the calling thread
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Detach(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the thread is joinable
    ///
    /// \return true if the thread is joinable, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool Joinable(void) const = 0;
};

}   // namespace tkd
