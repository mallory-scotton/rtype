///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Core/Concurrency/IProcess.hpp>
#include <functional>
#include <sys/types.h>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
// De-activate this class for Windows platforms
///////////////////////////////////////////////////////////////////////////////
#ifndef TKD_SYSTEM_WINDOWS

///////////////////////////////////////////////////////////////////////////////
/// \brief Process implementation using fork and exec
///
///////////////////////////////////////////////////////////////////////////////
class FProcess : public IProcess
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Private class members
    ///////////////////////////////////////////////////////////////////////////
    std::function<void()> m_function;   //<! Function to execute in the process
    pid_t m_pid;                        //<! Process ID
    EProcessStatus m_status;            //<! Process status
    int m_returnValue;                  //<! Return value of the process

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor, initializes the process with a function to execute
    ///
    /// \param function Function to execute in the process
    ///
    ///////////////////////////////////////////////////////////////////////////
    explicit FProcess(std::function<void()> function);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    ~FProcess() override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Copy constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    FProcess(const FProcess&) = delete;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Move constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    FProcess(FProcess&&) = delete;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Copy assignment operator
    ///
    ///////////////////////////////////////////////////////////////////////////
    FProcess& operator=(const FProcess&) = delete;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Move assignment operator
    ///
    ///////////////////////////////////////////////////////////////////////////
    FProcess& operator=(FProcess&&) = delete;

private:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Update the process status based on the wait status
    ///
    /// \param status Status returned by waitpid
    ///
    ///////////////////////////////////////////////////////////////////////////
    void UpdateStatusFromWait(int status);

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Start the process
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Start(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Wait for the process to finish
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Wait(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the process is currently running
    ///
    /// \return True if the process is running, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool IsRunning(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the process is a parent process
    ///
    /// \return True if the process is a parent, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool IsParent(void) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the process is a child process
    ///
    /// \return True if the process is a child, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool IsChild(void) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the return value of the process
    ///
    /// \return Return value of the process
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual int GetReturnValue(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current status of the process
    ///
    /// \return The current status of the process
    ///
    ///////////////////////////////////////////////////////////////////////////
    EProcessStatus GetStatus(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the process ID
    ///
    /// \return Process ID
    ///
    ///////////////////////////////////////////////////////////////////////////
    pid_t GetPid(void) const;
};

#endif

}   // namespace tkd
