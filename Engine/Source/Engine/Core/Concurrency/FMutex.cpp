namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
FMutex::FMutex(void)
    : m_mutex()
{}

///////////////////////////////////////////////////////////////////////////////
FMutex::operator std::mutex&(void) { return m_mutex; }

///////////////////////////////////////////////////////////////////////////////
void FMutex::Lock(void) { m_mutex.lock(); }

///////////////////////////////////////////////////////////////////////////////
void FMutex::Unlock(void) { m_mutex.unlock(); }

///////////////////////////////////////////////////////////////////////////////
bool FMutex::TryLock(void) { return m_mutex.try_lock(); }

///////////////////////////////////////////////////////////////////////////////
std::mutex& FMutex::GetNativeMutex(void) { return m_mutex; }

}   // namespace tkd
