///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Represents a 2D view in the world space.
///
///////////////////////////////////////////////////////////////////////////////
class FView
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FVector2 m_center;       //<! The center of the view in world coordinates.
    FVector2 m_size;         //<! The size of the view.
    float m_rotation;        //<! The rotation of the view in degrees.
    FRectangle m_viewport;   //<! The viewport rectangle.

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor. Initializes the view with default
    /// parameters.
    ///
    ///////////////////////////////////////////////////////////////////////////
    FView(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor. Initializes the view with the given rectangle.
    ///
    /// \param rectangle The rectangle defining the view's area.
    ///
    ///////////////////////////////////////////////////////////////////////////
    FView(const FRectangle& rectangle);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor. Initializes the view with the given center and
    /// size.
    ///
    /// \param center The center of the view.
    /// \param size The size of the view.
    ///
    ///////////////////////////////////////////////////////////////////////////
    FView(const FVector2& center, const FVector2& size);

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the viewport rectangle.
    ///
    /// \param x The x-coordinate of the center.
    /// \param y The y-coordinate of the center.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetCenter(float x, float y);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the center of the view.
    ///
    /// \param center The new center of the view.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetCenter(const FVector2& center);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the size of the view.
    ///
    /// \param width The new width of the view.
    /// \param height The new height of the view.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetSize(float width, float height);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the size of the view.
    ///
    /// \param size The new size of the view.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetSize(const FVector2& size);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the rotation of the view.
    ///
    /// \param angle The new rotation angle in degrees.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetRotation(float angle);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the rotation of the view.
    ///
    /// \param rotation The new rotation of the view.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetRotation(const FRotator2D& rotation);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the viewport rectangle.
    ///
    /// \param viewport The new viewport rectangle.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetViewport(const FRectangle& viewport);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Resets the view to the given rectangle.
    ///
    /// \param rectangle The rectangle defining the new view area.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Reset(const FRectangle& rectangle);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the center of the view.
    ///
    /// \return The center of the view.
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FVector2& GetCenter(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the size of the view.
    ///
    /// \return The size of the view.
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FVector2& GetSize(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the rotation angle of the view in degrees.
    ///
    /// \return The rotation angle in degrees.
    ///
    ///////////////////////////////////////////////////////////////////////////
    float GetRotation(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the rotation of the view.
    ///
    /// \return The rotation of the view.
    ///
    ///////////////////////////////////////////////////////////////////////////
    FRotator2D GetRotator(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the viewport rectangle.
    ///
    /// \return The viewport rectangle.
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FRectangle& GetViewport(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the position of the view.
    ///
    /// \param position The new position of the view.
    /// \param size The new size of the view.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Move(float offsetX, float offsetY);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Moves the view by the given offset.
    ///
    /// \param offset The offset to move the view by.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Move(const FVector2& offset);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Rotates the view by the given angle.
    ///
    /// \param angle The angle to rotate the view by in degrees.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Rotate(float angle);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Rotates the view by the given rotator.
    ///
    /// \param rotation The rotator to rotate the view by.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Rotate(const FRotator2D& rotation);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Zooms the view by the given factor.
    ///
    /// \param factor The zoom factor. Values > 1 will zoom out, values < 1
    /// will zoom in.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Zoom(float factor);
};

}   // namespace tkd
