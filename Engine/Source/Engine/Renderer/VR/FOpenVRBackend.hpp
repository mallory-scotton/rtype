#if TKD_ENGINE_CLIENT
    #include <openvr/openvr.h>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd::VR
///////////////////////////////////////////////////////////////////////////////
namespace tkd::VR
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Interface for VR backend implementations using OpenVR
///
///////////////////////////////////////////////////////////////////////////////
class FOpenVRBackend : public IVRBackend
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    vr::IVRSystem* m_system;   //<! Pointer to the OpenVR system interface
    vr::TrackedDevicePose_t
        m_poses[vr::k_unMaxTrackedDeviceCount];   //<! Array of tracked device
                                                  // poses
    int m_controllerIndices[2];   //<! Indices of left and right controllers

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    FOpenVRBackend(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    ~FOpenVRBackend() override;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Initializes the VR backend
    ///
    /// \return True if initialization was successful, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool Initialize(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Shuts down the VR backend
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Shutdown(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Checks if a Head-Mounted Display (HMD) is present
    ///
    /// \return True if an HMD is present, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool IsHMDPresent(void) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Retrieves the VR specifications
    ///
    /// \return VRSpecs structure containing the VR specifications
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FVRSpecs GetSpecs(void) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the projection matrix for a given eye
    ///
    /// \param eye Eye identifier (left or right)
    /// \param nearClip Near clipping plane distance
    /// \param farClip Far clipping plane distance
    ///
    /// \return Projection matrix as FMatrix4x4
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FMatrix4x4 GetProjectionMatrix(
        EEye eye, Float32 nearClip, Float32 farClip
    ) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the eye-to-head transformation matrix
    ///
    /// \param eye Eye identifier (left or right)
    ///
    /// \return Transformation matrix as FMatrix4x4
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FMatrix4x4 GetEyeToHeadTransform(EEye eye) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Waits for vertical synchronization
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void WaitForSync(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Updates the poses of the HMD and controllers
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void UpdatePoses(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Processes VR system events
    ///
    /// \return Vector of VR events that occurred since last poll
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual std::vector<FVREvent> ProcessEvents(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Retrieves the current pose of the HMD
    ///
    /// \return FPose structure representing the HMD pose
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FPose GetHMDPose(void) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Retrieves the current state of a controller
    ///
    /// \param hand Hand identifier (left or right)
    ///
    /// \return FControllerState structure representing the controller state
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FControllerState GetControllerState(EHand hand) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Checks if a specific button is pressed on a controller
    ///
    /// \param hand The hand identifier (left or right)
    /// \param button The button to check
    ///
    /// \return True if the button is pressed, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool IsButtonPressed(EHand hand, EButton button) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Triggers a haptic pulse on a controller
    ///
    /// \param hand Hand identifier (left or right)
    /// \param intensity Pulse intensity
    /// \param duration Pulse duration in seconds
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void TriggerHapticPulse(
        EHand hand, Float32 intensity, Float32 duration
    ) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Submits a rendered frame for a specific eye
    ///
    /// \param eye Eye identifier (left or right)
    /// \param target Render target containing the frame to submit
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SubmitFrame(EEye eye, const FRenderTarget& target) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Retrieves the size of the play area
    ///
    /// \return FVector3 representing the play area size
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FVector3 GetPlayAreaSize(void) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Recenters the seated position of the VR system
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void RecenterSeatedPosition(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the tracking universe/space
    ///
    /// \param universe The tracking universe to use
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetTrackingUniverse(ETrackingUniverse universe) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current tracking universe/space
    ///
    /// \return The current tracking universe
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ETrackingUniverse GetTrackingUniverse(void) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get controller battery level
    ///
    /// \param hand The hand identifier (left or right)
    ///
    /// \return Battery level as a percentage (0.0 to 1.0), or -1.0 if not
    /// available
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Float32 GetControllerBattery(EHand hand) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the corners of the play area bounds
    ///
    /// \return Vector of corner points (typically 4 corners for a rectangle)
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual std::vector<FVector3> GetPlayAreaBounds(void) const override;

private:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Convert OpenVR Pose to FPose
    ///
    /// \param pose OpenVR tracked device pose
    ///
    /// \return FPose structure
    ///
    ///////////////////////////////////////////////////////////////////////////
    FPose ConvertPose(const vr::TrackedDevicePose_t& pose) const;
};

}   // namespace tkd::VR

#endif
