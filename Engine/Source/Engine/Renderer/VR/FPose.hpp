///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd::VR
///////////////////////////////////////////////////////////////////////////////
namespace tkd::VR
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Class representing the pose of a VR device
///
///////////////////////////////////////////////////////////////////////////////
class FPose
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FVector3 position;          //<! Position vector
    FQuaternion rotation;       //<! Rotation quaternion
    FVector3 velocity;          //<! Linear velocity vector
    FVector3 angularVelocity;   //<! Angular velocity vector
    Bool isValid;               //<! Validity flag

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor - initializes pose to default values
    ///
    ///////////////////////////////////////////////////////////////////////////
    FPose(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Parameterized constructor - initializes pose with given values
    ///
    /// \param pos Position vector
    /// \param rot Rotation quaternion
    /// \param vel Linear velocity vector
    /// \param angVel Angular velocity vector
    /// \param valid Validity flag
    ///
    ///////////////////////////////////////////////////////////////////////////
    FPose(
        const FVector3& pos,
        const FQuaternion& rot,
        const FVector3& vel,
        const FVector3& angVel,
        Bool valid
    );

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get transformation matrix representing the pose
    ///
    /// \return 4x4 transformation matrix
    ///
    ///////////////////////////////////////////////////////////////////////////
    FMatrix4x4 GetMatrix(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get view matrix for the pose
    ///
    /// \return 4x4 view matrix
    ///
    ///////////////////////////////////////////////////////////////////////////
    FMatrix4x4 GetViewMatrix(void) const;
};

}   // namespace tkd::VR
