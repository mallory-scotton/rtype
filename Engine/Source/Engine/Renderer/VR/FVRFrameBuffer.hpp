#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/VR/FRenderTarget.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd::VR
///////////////////////////////////////////////////////////////////////////////
namespace tkd::VR
{

///////////////////////////////////////////////////////////////////////////////
/// \brief VR Framebuffer wrapper for managing render targets
///
/// This class manages OpenGL framebuffers used for VR rendering, including
/// support for MSAA (multi-sample anti-aliasing) and resolve operations.
///
/// \warning This class is not thread-safe. All OpenGL operations must be
/// performed on the same thread that created the OpenGL context.
///
///////////////////////////////////////////////////////////////////////////////
class FVRFrameBuffer
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    UInt32 m_width;                //<! Framebuffer width
    UInt32 m_height;               //<! Framebuffer height
    UInt32 m_framebuffer;          //<! Framebuffer ID
    UInt32 m_depthBuffer;          //<! Depth buffer ID
    UInt32 m_renderTexture;        //<! Texture ID
    UInt32 m_resolveFramebuffer;   //<! Resolve framebuffer ID
    UInt32 m_resolveTexture;       //<! Resolve texture ID
    UInt32 m_msaaSamples;          //<! Number of MSAA samples

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    FVRFrameBuffer(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor with width, height and MSAA samples
    ///
    /// \param width Framebuffer width
    /// \param height Framebuffer height
    /// \param msaaSamples Number of MSAA samples
    ///
    ///////////////////////////////////////////////////////////////////////////
    FVRFrameBuffer(UInt32 width, UInt32 height, UInt32 msaaSamples);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    ~FVRFrameBuffer();

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Create the framebuffer with given specifications
    ///
    /// \param width Framebuffer width
    /// \param height Framebuffer height
    /// \param msaaSamples Number of MSAA samples
    ///
    /// \return true if creation was successful, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    Bool Create(UInt32 width, UInt32 height, UInt32 msaaSamples);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Destroy the framebuffer
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Destroy(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Bind the framebuffer
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Bind(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Unbind the framebuffer
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Unbind(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Resolve the multisampled framebuffer to the resolve framebuffer
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Resolve(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the render target associated with this framebuffer
    ///
    /// \return FRenderTarget object representing the render target
    ///
    ///////////////////////////////////////////////////////////////////////////
    FRenderTarget GetRenderTarget(void) const;
};

}   // namespace tkd::VR
