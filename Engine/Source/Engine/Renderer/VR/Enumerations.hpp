#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd::VR
///////////////////////////////////////////////////////////////////////////////
namespace tkd::VR
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Enum for VR eyes
///
///////////////////////////////////////////////////////////////////////////////
enum class EEye
{
    Left = 0,   //<! Left eye
    Right = 1   //<! Right eye
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Enum for VR hands
///
///////////////////////////////////////////////////////////////////////////////
enum class EHand
{
    Left = 0,   //<! Left hand
    Right = 1   //<! Right hand
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Enum for VR controller buttons
///
///////////////////////////////////////////////////////////////////////////////
enum class EButton
{
    Trigger,    //<! Trigger button
    Grip,       //<! Grip button
    Menu,       //<! Menu button
    Touchpad,   //<! Touchpad button
    Joystick,   //<! Joystick button
    ButtonA,    //<! ButtonA
    ButtonB,    //<! ButtonB
    COUNT       //<! Total number of buttons
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Enum for VR tracking universe/space
///
///////////////////////////////////////////////////////////////////////////////
enum class ETrackingUniverse
{
    Seated,     //<! Seated tracking (limited movement, recenterable)
    Standing,   //<! Standing tracking (room-scale within chaperone bounds)
    RawAndUncalibrated   //<! Raw tracking data without calibration
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Enum for VR movement types
///
///////////////////////////////////////////////////////////////////////////////
enum class EMovementType
{
    None,      //<! No movement
    Smooth,    //<! Smooth movement
    Teleport   //<! Teleport movement
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Enum for VR turn types
///
///////////////////////////////////////////////////////////////////////////////
enum class ETurnType
{
    None,     //<! No turning
    Smooth,   //<! Smooth turning
    Snap      //<! Snap turning
};

}   // namespace tkd::VR
