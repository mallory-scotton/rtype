///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Containers.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Animations/FAnimation2D.hpp>
#include <Engine/Renderer/Animations/FAnimationTransition.hpp>
#include <type_traits>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Class representing the state of an animation.
///
///////////////////////////////////////////////////////////////////////////////
class FAnimationState
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Aliases
    ///////////////////////////////////////////////////////////////////////////
    using AnimationType =
        TVariant<FAnimation2D>;   //<! Type alias for the animation type

public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FString name;              //<! Name of the animation state
    AnimationType animation;   //<! The animation associated with this state
    TVector<FAnimationTransition>
        transitions;           //<! Possible transitions from this state
    Float32 playbackSpeed;     //<! Speed multiplier for playback
    bool allowInterruption;    //<! Whether this state can be interrupted

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    FAnimationState(void)
        : playbackSpeed(1.0f)
        , allowInterruption(true)
    {}

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor with name and animation
    ///
    /// \param name The name of the animation state
    /// \param animation The animation associated with this state
    ///
    ///////////////////////////////////////////////////////////////////////////
    FAnimationState(const FString& name, const AnimationType& animation)
        : name(name)
        , animation(animation)
        , playbackSpeed(1.0f)
        , allowInterruption(true)
    {}
};

}   // namespace tkd
