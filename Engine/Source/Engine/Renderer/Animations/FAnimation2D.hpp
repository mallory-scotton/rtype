///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Containers.hpp>
#include <Engine/Renderer/Animations/FAnimation2DFrame.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Class representing a 2D animation composed of multiple frames.
///
///////////////////////////////////////////////////////////////////////////////
class FAnimation2D
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    TVector<FAnimation2DFrame> m_frames;   //<! Frames of the animation
    FString m_name;                        //<! Name of the animation
    bool m_isLooping;                      //<! Whether the animation loops

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor with name and looping option.
    ///
    /// \param name The name of the animation.
    /// \param isLooping Whether the animation should loop.
    ///
    ///////////////////////////////////////////////////////////////////////////
    FAnimation2D(const FString& name = "", bool isLooping = true);

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Operator to access a specific frame
    ///
    /// \param index The index of the frame to access
    ///
    /// \return Reference to the frame at the specified index
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FAnimation2DFrame& operator[](SizeT index) const;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Add a frame to the animation
    ///
    /// \param frame The frame to add
    ///
    ///////////////////////////////////////////////////////////////////////////
    void AddFrame(const FAnimation2DFrame& frame);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Add a frame to the animation
    ///
    /// \param rect The texture rectangle for this frame
    /// \param duration Duration of this frame in seconds
    ///
    ///////////////////////////////////////////////////////////////////////////
    void AddFrame(const FRectanglei& rect, Float32 duration = 0.1f);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the number of frames
    ///
    /// \return The number of frames in this animation
    ///
    ///////////////////////////////////////////////////////////////////////////
    SizeT GetFrameCount(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get a specific frame
    ///
    /// \param index The index of the frame
    /// \return Reference to the frame
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FAnimation2DFrame& GetFrame(SizeT index) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the name of the animation
    ///
    /// \return The animation name
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FString& GetName(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the animation is looping
    ///
    /// \return True if looping, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool IsLooping(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set whether the animation loops
    ///
    /// \param isLooping Whether the animation should loop
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetLooping(bool isLooping);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get total duration of the animation
    ///
    /// \return Total duration in seconds
    ///
    ///////////////////////////////////////////////////////////////////////////
    Float32 GetTotalDuration(void) const;
};

}   // namespace tkd
