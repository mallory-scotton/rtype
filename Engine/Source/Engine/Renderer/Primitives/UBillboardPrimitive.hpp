#include <Engine/Config.hpp>
#include <Engine/Renderer/Interfaces/ITexture.hpp>
#include <Engine/Renderer/UPrimitive.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Billboard primitive class
///
///////////////////////////////////////////////////////////////////////////////
class UBillboardPrimitive : public UPrimitive
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    mutable ITexture* m_texture;   //<! Texture of the billboard

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor
    ///
    /// \param texture Texture of the billboard
    /// \param color Color of the billboard
    ///
    ///////////////////////////////////////////////////////////////////////////
    UBillboardPrimitive(
        ITexture* texture = nullptr, const FColor& color = FColor::White
    );

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~UBillboardPrimitive() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the primitive
    ///
    /// \param renderer Renderer to draw with
    /// \param states Additional render states
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Draw(
        IRenderer& renderer, FRenderStates states = FRenderStates()
    ) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the texture of the billboard
    ///
    /// \param texture New texture
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetTexture(ITexture* texture);
};

}   // namespace tkd
