///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Renderer/Interfaces/ITexture.hpp>
#include <Engine/Renderer/UPrimitive.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Chamfer cube primitive class with beveled edges
///
/// A chamfer cube is a cube with beveled/rounded edges instead of sharp
/// corners. The chamfer size parameter controls how much of the edge is
/// beveled, creating a smoother, more refined appearance.
///
///////////////////////////////////////////////////////////////////////////////
class UChamferCubePrimitive : public UPrimitive
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Members
    ///////////////////////////////////////////////////////////////////////////
    mutable ITexture* m_texture;   //<! Texture of the chamfer cube
    Float32 m_chamferSize;         //<! Size of the chamfer (0.0 to 0.5)
    SizeT m_segments;              //<! Number of segments for smooth corners

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor
    ///
    /// \param color Color of the chamfer cube
    /// \param chamferSize Size of the chamfer (0.0 to 0.5, default 0.1)
    /// \param segments Number of segments for rounding (default 4)
    ///
    ///////////////////////////////////////////////////////////////////////////
    UChamferCubePrimitive(
        const FColor& color = FColor::White,
        Float32 chamferSize = 0.1f,
        SizeT segments = 4
    );

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~UChamferCubePrimitive() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the primitive
    ///
    /// \param renderer Renderer to draw with
    /// \param states Additional render states
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Draw(
        IRenderer& renderer, FRenderStates states = FRenderStates()
    ) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the texture of the chamfer cube
    ///
    /// \param texture New texture
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetTexture(ITexture* texture);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the texture of the chamfer cube
    ///
    /// \return Pointer to the texture
    ///
    ///////////////////////////////////////////////////////////////////////////
    ITexture* GetTexture(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the chamfer size
    ///
    /// \param size New chamfer size (0.0 to 0.5)
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetChamferSize(Float32 size);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the chamfer size
    ///
    /// \return Current chamfer size
    ///
    ///////////////////////////////////////////////////////////////////////////
    Float32 GetChamferSize(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the number of segments for smoothing
    ///
    /// \param segments New segment count (minimum 1)
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetSegments(SizeT segments);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the number of segments
    ///
    /// \return Current segment count
    ///
    ///////////////////////////////////////////////////////////////////////////
    SizeT GetSegments(void) const;

private:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Update the vertices of the chamfer cube with texture coordinates
    ///
    /// Generates a chamfered cube geometry by creating beveled edges.
    /// Each corner is replaced with a small triangulated chamfer surface.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void UpdateVertices(void) override;
};

}   // namespace tkd
