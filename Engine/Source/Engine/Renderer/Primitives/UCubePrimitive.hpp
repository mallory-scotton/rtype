///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Renderer/Interfaces/ITexture.hpp>
#include <Engine/Renderer/UPrimitive.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Cube primitive class
///
///////////////////////////////////////////////////////////////////////////////
class UCubePrimitive : public UPrimitive
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    mutable ITexture* m_texture;   //<! Texture of the cube

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor
    ///
    /// \param color Color of the cube
    ///
    ///////////////////////////////////////////////////////////////////////////
    UCubePrimitive(const FColor& color = FColor::White);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~UCubePrimitive() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the primitive
    ///
    /// \param renderer Renderer to draw with
    /// \param states Additional render states
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Draw(
        IRenderer& renderer, FRenderStates states = FRenderStates()
    ) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the texture of the cube
    ///
    /// \param texture New texture
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetTexture(ITexture* texture);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the texture of the cube
    ///
    /// \return Pointer to the texture
    ///
    ///////////////////////////////////////////////////////////////////////////
    ITexture* GetTexture(void) const;

private:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Update the vertices of the cube with texture coordinates
    ///
    ///////////////////////////////////////////////////////////////////////////
    void UpdateVertices(void);
};

}   // namespace tkd
