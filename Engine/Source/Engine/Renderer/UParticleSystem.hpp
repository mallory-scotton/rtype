#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Interfaces.hpp>
#include <random>
#include <vector>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Types of particle emitters
///
///////////////////////////////////////////////////////////////////////////////
enum class EParticleEmitterType
{
    Point,    //<! Emit from a single point
    Sphere,   //<! Emit from sphere surface
    Box,      //<! Emit from box volume
    Cone      //<! Emit in cone shape
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Represents a single particle in the particle system
///
///////////////////////////////////////////////////////////////////////////////
class FParticle
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FVector3 position;
    FVector3 velocity;
    FColor color;
    float size;
    float lifetime;      // Current lifetime
    float maxLifetime;   // Total lifetime
    float rotation;      // For spinning particles
    float rotationSpeed;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the particle is still alive
    ///
    /// \return True if the particle's lifetime is greater than zero
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool IsAlive(void) const;
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Particle system for managing and rendering particles
///
///////////////////////////////////////////////////////////////////////////////
class UParticleSystem
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    std::vector<FParticle> m_particles;   //<! Active particles
    SizeT m_maxParticles;                 //<! Maximum number of particles
    ITexture* m_texture;                  //<! Texture for particles

    // Emitter properties
    FVector3 m_emitterPosition;           //<! Position of the emitter
    EParticleEmitterType m_emitterType;   //<! Type of emitter
    float m_emitterRadius;                //<! Radius for sphere/box emitters

    // Particle spawn properties
    float m_lifetimeMin, m_lifetimeMax;   //<! Particle lifetime range
    float m_sizeMin, m_sizeMax;           //<! Particle size range
    float m_speedMin, m_speedMax;         //<! Particle speed range
    FColor m_colorStart, m_colorEnd;      //<! Particle color gradient
    FVector3 m_gravity;                   //<! Gravity affecting particles

    bool m_additiveBlending;              //<! Whether to use additive blending

    // Random number generation
    std::mt19937 m_rng;   //<! Mersenne Twister RNG
    std::uniform_real_distribution<float>
        m_dist;           //<! Uniform distribution [0,1]

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor
    ///
    /// \param maxParticles Maximum number of particles in the system
    /// \param texture Texture to use for particles
    ///
    ///////////////////////////////////////////////////////////////////////////
    UParticleSystem(SizeT maxParticles = 1000, ITexture* texture = nullptr);

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Update the particle system
    ///
    /// \param deltaTime Time elapsed since last update
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Update(float deltaTime);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the particle system
    ///
    /// \param renderer The renderer to draw with
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Draw(IRenderer& renderer);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Emit a number of particles immediately
    ///
    /// \param count Number of particles to emit
    ///
    ///////////////////////////////////////////////////////////////////////////
    void EmitParticles(SizeT count);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the emitter position
    ///
    /// \param position New position of the emitter
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetEmitterPosition(const FVector3& position);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the emitter type
    ///
    /// \param type New emitter type
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetEmitterType(EParticleEmitterType type);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the particle lifetime range
    ///
    /// \param min The minimum lifetime
    /// \param max The maximum lifetime
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetParticleLifetime(float min, float max);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the particle size range
    ///
    /// \param min The minimum size
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetParticleSize(float min, float max);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the particle speed range
    ///
    /// \param min The minimum speed
    /// \param max The maximum speed
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetParticleSpeed(float min, float max);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the particle color gradient
    ///
    /// \param startColor The starting color of particles
    /// \param endColor The ending color of particles
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetParticleColor(const FColor& startColor, const FColor& endColor);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the emitter radius
    ///
    /// \param radius The radius for sphere/box emitters
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetEmitterRadius(float radius);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the gravity affecting particles
    ///
    /// \param gravity The gravity vector
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetGravity(const FVector3& gravity);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the texture used for particles
    ///
    /// \param texture The texture to use for particles
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetTexture(ITexture* texture);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Enable or disable additive blending for particles
    ///
    /// \param additive True to enable additive blending, false for normal
    /// blending
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetAdditiveBlending(bool additive);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Clear all particles from the system
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Clear(void);

private:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Initialize a new particle with random properties
    ///
    /// \param particle The particle to initialize
    ///
    ///////////////////////////////////////////////////////////////////////////
    void InitializeParticle(FParticle& particle);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Generate a random direction vector
    ///
    /// \return A normalized random direction vector
    ///
    ///////////////////////////////////////////////////////////////////////////
    FVector3 GetRandomDirection(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Generate a random float between min and max
    ///
    /// \param min Minimum value
    /// \param max Maximum value
    ///
    /// \return Random float in the range [min, max]
    ///
    ///////////////////////////////////////////////////////////////////////////
    float RandomFloat(float min, float max);
};

}   // namespace tkd
