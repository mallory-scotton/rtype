///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Renderer/UPrimitive.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
UPrimitive::UPrimitive(EPrimitiveType type, const FColor& color)
    : m_primitiveType(type)
    , m_vertices()
    , m_color(color)
{}

///////////////////////////////////////////////////////////////////////////////
void UPrimitive::Draw(IRenderer& renderer, FRenderStates states) const
{
    // State parameter is currently unused
    TKD_UNUSED(states);

    // Draw the vertices using the renderer
    renderer.Draw(m_vertices, m_primitiveType, GetTransform());
}

///////////////////////////////////////////////////////////////////////////////
const std::vector<FVertex>& UPrimitive::GetVertices(void) const
{
    return m_vertices;
}

///////////////////////////////////////////////////////////////////////////////
EPrimitiveType UPrimitive::GetPrimitiveType(void) const
{
    return m_primitiveType;
}

///////////////////////////////////////////////////////////////////////////////
const FColor& UPrimitive::GetColor(void) const { return m_color; }

///////////////////////////////////////////////////////////////////////////////
void UPrimitive::SetColor(const FColor& color)
{
    m_color = color;
    for (FVertex& vertex: m_vertices) { vertex.color = color; }
}

}   // namespace tkd
