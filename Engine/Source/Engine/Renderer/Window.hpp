#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Utils/EventEmitter.hpp>
#include <Engine/Core/Utils/Singleton.hpp>
#include <tuple>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
// Pre-declaration of IWindow class
///////////////////////////////////////////////////////////////////////////////
class IWindow;

///////////////////////////////////////////////////////////////////////////////
/// \brief Private namespace for window events
///
///////////////////////////////////////////////////////////////////////////////
template <>
struct TEvents<IWindow>
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct Opened
    {};

    ///////////////////////////////////////////////////////////////////////////
    /// \brief
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct Closed
    {};

    ///////////////////////////////////////////////////////////////////////////
    /// \brief
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct Resized
    {};

    ///////////////////////////////////////////////////////////////////////////
    /// \brief
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct LostFocus
    {};

    ///////////////////////////////////////////////////////////////////////////
    /// \brief
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct GainedFocus
    {};

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief
    ///
    ///////////////////////////////////////////////////////////////////////////
    using All = std::tuple<Opened, Closed, Resized, LostFocus, GainedFocus>;
};

///////////////////////////////////////////////////////////////////////////////
/// \brief
///
///////////////////////////////////////////////////////////////////////////////
class IWindow
    : public TEventEmitter<TEvents<IWindow>::All>
    , public Singleton<IWindow>
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Alias for event types
    ///
    ///////////////////////////////////////////////////////////////////////////
    using Events = TEvents<IWindow>;

public:
    void Start(void)
    {
        Emit(TEvents<IWindow>::Opened{});
    }
};

} // !namespace tkd
