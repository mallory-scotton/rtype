///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Assets/UResourceHandle.hpp>
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Interfaces/IRenderer.hpp>
#include <Engine/Renderer/USprite.hpp>
#include <vector>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Text rendering using bitmap font sprite sheet
///
/// Supports ASCII characters from space (32) to tilde (126)
/// Font layout: 32 characters per row, 3 rows total
///
///////////////////////////////////////////////////////////////////////////////
class UTextShape
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Members
    ///////////////////////////////////////////////////////////////////////////
    FString m_text;                   ///< Text to display
    FVector2 m_position;              ///< Position of the text
    FVector2 m_characterSize;         ///< Display size (on screen)
    FVector2 m_sourceCharacterSize;   ///< Source size (in texture file)
    Float32 m_spacing;              ///< Horizontal spacing between characters
    FColor m_color;                 ///< Text color
    FTextureHandle m_fontTexture;   ///< Font sprite sheet texture
    FilePath m_fontPath;            ///< Path to font texture
    FVector2 m_origin;              ///< Origin for positioning

    // Font sprite sheet layout
    static constexpr Int32 CHARS_PER_ROW = 32;
    static constexpr Int32 TOTAL_ROWS = 3;
    static constexpr Int32 FIRST_CHAR = 32;   // Space character
    static constexpr Int32 LAST_CHAR = 126;   // Tilde character

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    UTextShape();

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the font sprite sheet
    ///
    /// \param fontPath Path to the font texture (PNG with ASCII chars 32-126)
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetFont(const FilePath& fontPath);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current font path
    ///
    /// \return Font texture path
    ///
    ////////////////////////////////////////////////////////////////////////////
    const FilePath& GetFont() const { return m_fontPath; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the text string to display
    ///
    /// \param text The text string
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetString(const FString& text);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current text string
    ///
    /// \return The text string
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FString& GetString() const { return m_text; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the position of the text
    ///
    /// \param position Position in screen space
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetPosition(const FVector2& position);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the position of the text
    ///
    /// \return Position in screen space
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FVector2& GetPosition() const { return m_position; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the size of each character
    ///
    /// \param size Character width and height
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetCharacterSize(const FVector2& size);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the character size
    ///
    /// \return Character size
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FVector2& GetCharacterSize() const { return m_characterSize; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set spacing between characters
    ///
    /// \param spacing Horizontal spacing in pixels
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetSpacing(Float32 spacing);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get spacing between characters
    ///
    /// \return Horizontal spacing
    ///
    ///////////////////////////////////////////////////////////////////////////
    Float32 GetSpacing() const { return m_spacing; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the text color
    ///
    /// \param color RGBA color
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetColor(const FColor& color);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the text color
    ///
    /// \return Current color
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FColor& GetColor() const { return m_color; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the origin point for text positioning
    ///
    /// \param origin The new origin point
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetOrigin(const FVector2& origin);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the origin point
    ///
    /// \return Current origin offset
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FVector2& GetOrigin() const { return m_origin; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Calculate total width of the text
    ///
    /// \return Width in pixels
    ///
    ///////////////////////////////////////////////////////////////////////////
    Float32 GetTextWidth() const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the text
    ///
    /// \param renderer The renderer to use
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Draw(IRenderer& renderer) const;

private:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get texture coordinates for a character
    ///
    /// \param character The ASCII character
    /// \return Rectangle defining the character's position in the sprite sheet
    ///
    ///////////////////////////////////////////////////////////////////////////
    FRectanglei GetCharacterRect(char character) const;
};

}   // namespace tkd
