///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Renderer/FView.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
FView::FView(void)
    : m_center(FVector2::Zero)
    , m_size(FVector2::Zero)
    , m_rotation(0.0f)
    , m_viewport(FRectangle::Zero)
{}

///////////////////////////////////////////////////////////////////////////////
FView::FView(const FRectangle& rectangle)
    : m_center(
          rectangle.left + rectangle.width * 0.5f,
          rectangle.top + rectangle.height * 0.5f
      )
    , m_size(rectangle.width, rectangle.height)
    , m_rotation(0.0f)
    , m_viewport(FRectangle::Zero)
{}

///////////////////////////////////////////////////////////////////////////////
FView::FView(const FVector2& center, const FVector2& size)
    : m_center(center)
    , m_size(size)
    , m_rotation(0.0f)
    , m_viewport(FRectangle::Zero)
{}

///////////////////////////////////////////////////////////////////////////////
void FView::SetCenter(float x, float y)
{
    m_center.x = x;
    m_center.y = y;
}

///////////////////////////////////////////////////////////////////////////////
void FView::SetCenter(const FVector2& center) { m_center = center; }

///////////////////////////////////////////////////////////////////////////////
void FView::SetSize(float width, float height)
{
    m_size.x = width;
    m_size.y = height;
}

///////////////////////////////////////////////////////////////////////////////
void FView::SetSize(const FVector2& size) { m_size = size; }

///////////////////////////////////////////////////////////////////////////////
void FView::SetRotation(float angle) { m_rotation = angle; }

///////////////////////////////////////////////////////////////////////////////
void FView::SetRotation(const FRotator2D& rotation)
{
    m_rotation = rotation.GetAngle();
}

///////////////////////////////////////////////////////////////////////////////
void FView::SetViewport(const FRectangle& viewport) { m_viewport = viewport; }

///////////////////////////////////////////////////////////////////////////////
void FView::Reset(const FRectangle& rectangle)
{
    m_center.x = rectangle.left + rectangle.width * 0.5f;
    m_center.y = rectangle.top + rectangle.height * 0.5f;
    m_size.x = rectangle.width;
    m_size.y = rectangle.height;
    m_rotation = 0.0f;
}

///////////////////////////////////////////////////////////////////////////////
const FVector2& FView::GetCenter(void) const { return m_center; }

///////////////////////////////////////////////////////////////////////////////
const FVector2& FView::GetSize(void) const { return m_size; }

///////////////////////////////////////////////////////////////////////////////
float FView::GetRotation(void) const { return m_rotation; }

///////////////////////////////////////////////////////////////////////////////
FRotator2D FView::GetRotator(void) const { return FRotator2D(m_rotation); }

///////////////////////////////////////////////////////////////////////////////
const FRectangle& FView::GetViewport(void) const { return m_viewport; }

///////////////////////////////////////////////////////////////////////////////
void FView::Move(float offsetX, float offsetY)
{
    m_center.x += offsetX;
    m_center.y += offsetY;
}

///////////////////////////////////////////////////////////////////////////////
void FView::Move(const FVector2& offset)
{
    m_center.x += offset.x;
    m_center.y += offset.y;
}

///////////////////////////////////////////////////////////////////////////////
void FView::Rotate(float angle) { m_rotation += angle; }

///////////////////////////////////////////////////////////////////////////////
void FView::Rotate(const FRotator2D& rotation)
{
    m_rotation += rotation.GetAngle();
}

///////////////////////////////////////////////////////////////////////////////
void FView::Zoom(float factor)
{
    if (factor > 0.0f)
    {
        m_size.x /= factor;
        m_size.y /= factor;
    }
}

}   // namespace tkd
