///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Audio/SFML/AudioListener.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd::SFML
///////////////////////////////////////////////////////////////////////////////
namespace tkd::SFML
{

#if TKD_ENGINE_CLIENT

///////////////////////////////////////////////////////////////////////////////
AudioListener::AudioListener(void)
    : m_velocity(FVector3::Zero)
    , m_globalVolume(1.0f)
{}

///////////////////////////////////////////////////////////////////////////////
void AudioListener::SetPosition(const FVector3& position)
{
    sf::Listener::setPosition(position.x, position.y, position.z);
}

///////////////////////////////////////////////////////////////////////////////
FVector3 AudioListener::GetPosition(void) const
{
    sf::Vector3f pos = sf::Listener::getPosition();
    return FVector3(pos.x, pos.y, pos.z);
}

///////////////////////////////////////////////////////////////////////////////
void AudioListener::SetVelocity(const FVector3& velocity)
{
    m_velocity = velocity;
}

///////////////////////////////////////////////////////////////////////////////
FVector3 AudioListener::GetVelocity(void) const { return m_velocity; }

///////////////////////////////////////////////////////////////////////////////
void AudioListener::SetOrientation(const FVector3& forward, const FVector3& up)
{
    sf::Listener::setDirection(forward.x, forward.y, forward.z);
    sf::Listener::setUpVector(up.x, up.y, up.z);
}

///////////////////////////////////////////////////////////////////////////////
void AudioListener::GetOrientation(FVector3& forward, FVector3& up) const
{
    sf::Vector3f dir = sf::Listener::getDirection();
    sf::Vector3f upVec = sf::Listener::getUpVector();
    forward = FVector3(dir.x, dir.y, dir.z);
    up = FVector3(upVec.x, upVec.y, upVec.z);
}

///////////////////////////////////////////////////////////////////////////////
void AudioListener::SetGlobalVolume(Float32 volume)
{
    m_globalVolume = volume;
    sf::Listener::setGlobalVolume(volume * 100.0f);
}

///////////////////////////////////////////////////////////////////////////////
Float32 AudioListener::GetGlobalVolume(void) const { return m_globalVolume; }

#endif

}   // namespace tkd::SFML
