///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Audio/SFML/AudioStream.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd::SFML
///////////////////////////////////////////////////////////////////////////////
namespace tkd::SFML
{

#if TKD_ENGINE_CLIENT

///////////////////////////////////////////////////////////////////////////////
Bool AudioStream::OpenFromFile(const FilePath& filePath)
{
    return m_music.openFromFile(filePath.string());
}

///////////////////////////////////////////////////////////////////////////////
Bool AudioStream::OpenFromMemory(const Byte* data, SizeT size)
{
    return m_music.openFromMemory(data, size);
}

///////////////////////////////////////////////////////////////////////////////
Bool AudioStream::OpenFromMemory(const std::vector<Byte>& data)
{
    return m_music.openFromMemory(data.data(), data.size());
}

///////////////////////////////////////////////////////////////////////////////
Bool AudioStream::OpenFromAsset(const UAsset* asset)
{
    if (asset == nullptr || asset->GetData().empty()) { return false; }
    return m_music.openFromMemory(
        asset->GetData().data(), asset->GetData().size()
    );
}

///////////////////////////////////////////////////////////////////////////////
void AudioStream::Play(void) { m_music.play(); }

///////////////////////////////////////////////////////////////////////////////
void AudioStream::Pause(void) { m_music.pause(); }

///////////////////////////////////////////////////////////////////////////////
void AudioStream::Stop(void) { m_music.stop(); }

///////////////////////////////////////////////////////////////////////////////
EAudioSourceState AudioStream::GetState(void) const
{
    switch (m_music.getStatus())
    {
    case sf::SoundSource::Stopped: return EAudioSourceState::Stopped;
    case sf::SoundSource::Paused : return EAudioSourceState::Paused;
    case sf::SoundSource::Playing: return EAudioSourceState::Playing;
    default                      : return EAudioSourceState::Stopped;
    }
}

///////////////////////////////////////////////////////////////////////////////
Bool AudioStream::IsPlaying(void) const
{
    return m_music.getStatus() == sf::SoundSource::Playing;
}

///////////////////////////////////////////////////////////////////////////////
Bool AudioStream::IsPaused(void) const
{
    return m_music.getStatus() == sf::SoundSource::Paused;
}

///////////////////////////////////////////////////////////////////////////////
Bool AudioStream::IsStopped(void) const
{
    return m_music.getStatus() == sf::SoundSource::Stopped;
}

///////////////////////////////////////////////////////////////////////////////
void AudioStream::SetVolume(Float32 volume)
{
    m_music.setVolume(volume * 100.0f);
}

///////////////////////////////////////////////////////////////////////////////
void AudioStream::SetVolume(UInt32 volume)
{
    m_music.setVolume(static_cast<Float32>(volume));
}

///////////////////////////////////////////////////////////////////////////////
Float32 AudioStream::GetVolume(void) const
{
    return m_music.getVolume() / 100.0f;
}

///////////////////////////////////////////////////////////////////////////////
void AudioStream::SetLooping(Bool loop) { m_music.setLoop(loop); }

///////////////////////////////////////////////////////////////////////////////
Bool AudioStream::IsLooping(void) const { return m_music.getLoop(); }

///////////////////////////////////////////////////////////////////////////////
Float32 AudioStream::GetDuration(void) const
{
    return m_music.getDuration().asSeconds();
}

///////////////////////////////////////////////////////////////////////////////
void AudioStream::SetPlaybackPosition(Float32 position)
{
    m_music.setPlayingOffset(sf::seconds(position));
}

///////////////////////////////////////////////////////////////////////////////
Float32 AudioStream::GetPlaybackPosition(void) const
{
    return m_music.getPlayingOffset().asSeconds();
}

#endif

}   // namespace tkd::SFML
