#if TKD_ENGINE_CLIENT
    #include <SFML/Audio.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd::SFML
///////////////////////////////////////////////////////////////////////////////
namespace tkd::SFML
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Audio listener implementation using SFML.
///
///////////////////////////////////////////////////////////////////////////////
class AudioListener : public IAudioListener
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FVector3 m_velocity;      //<! The velocity of the listener.
    Float32 m_globalVolume;   //<! The global volume of the listener.

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor.
    ///
    ///////////////////////////////////////////////////////////////////////////
    AudioListener(void);

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the position of the audio listener.
    ///
    /// \param position The position as a FVector3.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetPosition(const FVector3& position) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the position of the audio listener.
    ///
    /// \return The position as a FVector3.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FVector3 GetPosition(void) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the velocity of the audio listener.
    ///
    /// \param velocity The velocity as a FVector3.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetVelocity(const FVector3& velocity) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the velocity of the audio listener.
    ///
    /// \return The velocity as a FVector3.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FVector3 GetVelocity(void) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the orientation of the audio listener.
    ///
    /// \param forward The forward vector of the listener.
    /// \param up The up vector of the listener.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void
        SetOrientation(const FVector3& forward, const FVector3& up) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the orientation of the audio listener.
    ///
    /// \return The forward and up vectors of the listener.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void
        GetOrientation(FVector3& forward, FVector3& up) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the global volume of the audio listener.
    ///
    /// \param volume The global volume as a Float32.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetGlobalVolume(Float32 volume) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the global volume of the audio listener.
    ///
    /// \return The global volume as a Float32.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Float32 GetGlobalVolume(void) const override;
};

}   // namespace tkd::SFML

#endif
