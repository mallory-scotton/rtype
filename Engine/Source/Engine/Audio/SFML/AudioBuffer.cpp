///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Audio/SFML/AudioBuffer.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd::SFML
///////////////////////////////////////////////////////////////////////////////
namespace tkd::SFML
{

#if TKD_ENGINE_CLIENT

///////////////////////////////////////////////////////////////////////////////
Bool AudioBuffer::LoadFromAsset(const UAsset* asset)
{
    if (asset == nullptr || asset->GetData().empty()) { return false; }
    return m_buffer.loadFromMemory(
        asset->GetData().data(), asset->GetData().size()
    );
}

///////////////////////////////////////////////////////////////////////////////
Bool AudioBuffer::LoadFromFile(const FilePath& filePath)
{
    return m_buffer.loadFromFile(filePath.string());
}

///////////////////////////////////////////////////////////////////////////////
Bool AudioBuffer::LoadFromMemory(const std::vector<Byte>& data)
{
    if (data.empty()) { return false; }
    return m_buffer.loadFromMemory(data.data(), data.size());
}

///////////////////////////////////////////////////////////////////////////////
Bool AudioBuffer::LoadFromMemory(const Byte* data, const SizeT size)
{
    if (data == nullptr || size == 0) { return false; }
    return m_buffer.loadFromMemory(data, size);
}

///////////////////////////////////////////////////////////////////////////////
SizeT AudioBuffer::GetSampleCount(void) const
{
    return static_cast<SizeT>(m_buffer.getSampleCount());
}

///////////////////////////////////////////////////////////////////////////////
Int16* AudioBuffer::GetSamples(void) { return (Int16*)m_buffer.getSamples(); }

///////////////////////////////////////////////////////////////////////////////
Float32 AudioBuffer::GetDuration(void) const
{
    return m_buffer.getDuration().asSeconds();
}

///////////////////////////////////////////////////////////////////////////////
UInt32 AudioBuffer::GetSampleRate(void) const
{
    return m_buffer.getSampleRate();
}

///////////////////////////////////////////////////////////////////////////////
UInt32 AudioBuffer::GetChannelCount(void) const
{
    return m_buffer.getChannelCount();
}

///////////////////////////////////////////////////////////////////////////////
void* AudioBuffer::GetNativeHandle(void) const { return (void*)&m_buffer; }

#endif

}   // namespace tkd::SFML
