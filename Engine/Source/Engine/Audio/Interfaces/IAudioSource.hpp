#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Audio/Interfaces/IAudioBuffer.hpp>
#include <Engine/Config.hpp>
#include <Engine/Core.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Enumeration for audio source states.
///
///////////////////////////////////////////////////////////////////////////////
enum class EAudioSourceState
{
    Stopped,   //<! Not playing
    Playing,   //<! Currently playing
    Paused     //<! Paused
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Enumeration for attenuation models.
///
///////////////////////////////////////////////////////////////////////////////
enum class EAttenuationModel
{
    None,         //<! No distance attenuation
    Inverse,      //<! 1 / distance
    Linear,       //<! Linear fade over distance
    Exponential   //<! Exponential decay
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Interface for audio source management.
///
/// This interface defines the methods for controlling audio playback,
/// setting audio properties, and managing 3D audio characteristics.
///
///////////////////////////////////////////////////////////////////////////////
class IAudioSource
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default destructor.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~IAudioSource() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Play the audio source.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Play(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Pause the audio source.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Pause(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Stop the audio source.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Stop(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current state of the audio source.
    ///
    /// \return Current state of the audio source.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual EAudioSourceState GetState(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the audio source is currently playing.
    ///
    /// \return True if playing, false otherwise.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Bool IsPlaying(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the audio source is currently paused.
    ///
    /// \return True if paused, false otherwise.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Bool IsPaused(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the audio source is currently stopped.
    ///
    /// \return True if stopped, false otherwise.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Bool IsStopped(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the audio buffer for the source.
    ///
    /// \param buffer Audio buffer to set.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetBuffer(TSharedPtr<IAudioBuffer> buffer) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the audio buffer associated with the source.
    ///
    /// \return Shared pointer to the audio buffer.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual TSharedPtr<IAudioBuffer> GetBuffer(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the volume of the audio source.
    ///
    /// \param volume Volume level (0.0 to 1.0).
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetVolume(Float32 volume) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the volume of the audio source.
    ///
    /// \param volume Volume level (0 to 100).
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetVolume(UInt32 volume) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the volume of the audio source.
    ///
    /// \return Volume level (0.0 to 1.0).
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Float32 GetVolume(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the pitch of the audio source.
    ///
    /// \param pitch Pitch level (default is 1.0).
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetPitch(Float32 pitch) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the pitch of the audio source.
    ///
    /// \return Pitch level (default is 1.0).
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Float32 GetPitch(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set whether the audio source should loop.
    ///
    /// \param loop True to enable looping, false to disable.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetLooping(Bool loop) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the audio source is set to loop.
    ///
    /// \return True if looping is enabled, false otherwise.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Bool IsLooping(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the playback position of the audio source in seconds.
    ///
    /// \param seconds Playback position in seconds.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetPlaybackPosition(Float32 seconds) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current playback position of the audio source in
    /// seconds.
    ///
    /// \return Playback position in seconds.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Float32 GetPlaybackPosition(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the 3D position of the audio source.
    ///
    /// \param position 3D position vector.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetPosition(const FVector3& position) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the 3D position of the audio source.
    ///
    /// \return 3D position vector.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FVector3 GetPosition(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the velocity of the audio source.
    ///
    /// \param velocity 3D velocity vector.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetVelocity(const FVector3& velocity) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the velocity of the audio source.
    ///
    /// \return 3D velocity vector.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FVector3 GetVelocity(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the direction of the audio source.
    ///
    /// \param direction 3D direction vector.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetDirection(const FVector3& direction) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the direction of the audio source.
    ///
    /// \return 3D direction vector.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FVector3 GetDirection(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the inner and outer cone angles for directional audio.
    ///
    /// \param innerAngle The inner cone angle in degrees.
    /// \param outerAngle The outer cone angle in degrees.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetConeAngles(Float32 innerAngle, Float32 outerAngle) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the outer cone gain for directional audio.
    ///
    /// \param gain Outer cone gain in decibels.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetConeOuterGain(Float32 gain) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set whether the audio source is spatialized.
    ///
    /// \param spatial True to enable spatialization, false to disable.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetSpatial(Bool spatial) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the audio source is spatialized.
    ///
    /// \return True if spatialized, false otherwise.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Bool IsSpatial(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the attenuation model for the audio source.
    ///
    /// \param model Attenuation model to use.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetAttenuationModel(EAttenuationModel model) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the attenuation model of the audio source.
    ///
    /// \return Current attenuation model.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual EAttenuationModel GetAttenuationModel(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the minimum distance for attenuation calculations.
    ///
    /// \param distance Minimum distance value.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetMinDistance(Float32 distance) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the minimum distance for attenuation calculations.
    ///
    /// \return Minimum distance value.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Float32 GetMinDistance(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the maximum distance for attenuation calculations.
    ///
    /// \param distance Maximum distance value.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetMaxDistance(Float32 distance) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the maximum distance for attenuation calculations.
    ///
    /// \return Maximum distance value.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Float32 GetMaxDistance(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the rolloff factor for distance attenuation.
    ///
    /// \param factor Rolloff factor value.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetRolloffFactor(Float32 factor) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the rolloff factor for distance attenuation.
    ///
    /// \return Rolloff factor value.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Float32 GetRolloffFactor(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the Doppler effect factor.
    ///
    /// \param factor Doppler factor value.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetDopplerFactor(Float32 factor) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the Doppler effect factor.
    ///
    /// \return Doppler factor value.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Float32 GetDopplerFactor(void) const = 0;
};

}   // namespace tkd
