///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Assets/UAsset.hpp>
#include <Engine/Audio/Interfaces/IAudioSource.hpp>
#include <Engine/Config.hpp>
#include <vector>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Interface for audio streaming
///
/// This interface provides methods to stream audio from various sources
/// such as files, memory buffers, and assets. It also includes controls for
/// playback, volume, looping, and playback position.
///
///////////////////////////////////////////////////////////////////////////////
class IAudioStream
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Virtual destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~IAudioStream() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Open the audio stream from a file
    ///
    /// \param filePath The path to the audio file
    ///
    /// \return True if the stream was opened successfully, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool OpenFromFile(const FilePath& filePath) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Open the audio stream from a memory buffer
    ///
    /// \param data Pointer to the audio data
    /// \param size Size of the audio data in bytes
    ///
    /// \return True if the stream was opened successfully, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool OpenFromMemory(const Byte* data, SizeT size) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Open the audio stream from memory
    ///
    /// \param data Vector containing the audio data
    ///
    /// \return True if the stream was opened successfully, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool OpenFromMemory(const std::vector<Byte>& data) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Open the audio stream from an asset
    ///
    /// \param asset The asset to open the stream from
    ///
    /// \return True if the stream was opened successfully, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool OpenFromAsset(const UAsset* asset) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Play the audio stream
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Play(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Pause the audio stream
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Pause(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Stop the audio stream
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Stop(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current state of the audio source
    ///
    /// \return The current state (Stopped, Playing, Paused)
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual EAudioSourceState GetState(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the audio stream is currently playing.
    ///
    /// \return True if playing, false otherwise.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Bool IsPlaying(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the audio stream is currently paused.
    ///
    /// \return True if paused, false otherwise.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Bool IsPaused(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the audio stream is currently stopped.
    ///
    /// \return True if stopped, false otherwise.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Bool IsStopped(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the volume as a float between 0.0 and 1.0
    ///
    /// \param volume Volume level (0.0 - 1.0)
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetVolume(Float32 volume) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the volume as an integer between 0 and 100
    ///
    /// \param volume Volume level (0-100)
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetVolume(UInt32 volume) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current volume as a float between 0.0 and 1.0
    ///
    /// \return Current volume level (0.0 - 1.0)
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Float32 GetVolume(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set whether the audio stream should loop
    ///
    /// \param loop True to enable looping, false to disable
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetLooping(Bool loop) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the audio stream is set to loop
    ///
    /// \return True if looping is enabled, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Bool IsLooping(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the playback position in seconds
    ///
    /// \param seconds The playback position in seconds
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetPlaybackPosition(Float32 seconds) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current playback position in seconds
    ///
    /// \return The current playback position in seconds
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Float32 GetPlaybackPosition(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the total duration of the audio stream in seconds
    ///
    /// \return The total duration in seconds
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Float32 GetDuration(void) const = 0;
};

}   // namespace tkd
