namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Audio effect types
///
///////////////////////////////////////////////////////////////////////////////
enum class EAudioEffectType
{
    Reverb,       //<! Built-in reverb effect
    Echo,         //<! Built-in echo effect
    Chorus,       //<! Built-in chorus effect
    Distortion,   //<! Built-in distortion effect
    LowPass,      //<! Built-in low-pass filter
    HighPass,     //<! Built-in high-pass filter
    Custom        //<! Custom user-defined effect
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Reverb effect parameters
///
///////////////////////////////////////////////////////////////////////////////
struct FReverbParameters
{
    float density = 1.0f;
    float diffusion = 1.0f;
    float gain = 0.32f;
    float gainHF = 0.89f;
    float decayTime = 1.49f;
    float decayHFRatio = 0.83f;
    float reflectionsGain = 0.05f;
    float reflectionsDelay = 0.007f;
    float lateReverbGain = 1.26f;
    float lateReverbDelay = 0.011f;
    float airAbsorptionGainHF = 0.994f;
    float roomRolloffFactor = 0.0f;
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Audio effect interface
///
///////////////////////////////////////////////////////////////////////////////
class IAudioEffect
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Virtual destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~IAudioEffect() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the type of the effect
    ///
    /// \return The type of the effect
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual EAudioEffectType GetType(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Enable or disable the effect
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void SetEnabled(Bool enabled) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the effect is enabled
    ///
    /// \return True if the effect is enabled, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Bool IsEnabled(void) const = 0;
};

}   // namespace tkd
