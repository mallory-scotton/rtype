#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Assets/UAsset.hpp>
#include <Engine/Config.hpp>
#include <vector>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Interface for audio buffer implementations.
///
/// Provides methods to load audio data from various sources and retrieve
/// information about the audio data.
///
///////////////////////////////////////////////////////////////////////////////
class IAudioBuffer
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default virtual destructor.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~IAudioBuffer() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Load audio data from an asset.
    ///
    /// \param asset Asset to load audio data from.
    ///
    /// \return True if loading was successful, false otherwise.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Bool LoadFromAsset(const UAsset* asset) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Load audio data from a file.
    ///
    /// \param filePath Path to the audio file to load.
    ///
    /// \return True if loading was successful, false otherwise.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Bool LoadFromFile(const FilePath& filePath) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Load audio data from memory buffer.
    ///
    /// \param data Vector containing the raw audio data in memory.
    ///
    /// \return True if loading was successful, false otherwise.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Bool LoadFromMemory(const std::vector<Byte>& data) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Load audio data from raw memory buffer.
    ///
    /// \param data Pointer to the raw audio data in memory.
    /// \param size Size of the data buffer in bytes.
    ///
    /// \return True if loading was successful, false otherwise.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Bool LoadFromMemory(const Byte* data, const SizeT size) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the duration of the audio buffer in seconds.
    ///
    /// \return Duration in seconds.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Float32 GetDuration(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the sample rate of the audio buffer.
    ///
    /// \return Sample rate in Hz (e.g., 44100, 48000).
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual UInt32 GetSampleRate(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the total number of samples in the audio buffer.
    ///
    /// \return Total sample count.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual SizeT GetSampleCount(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get a pointer to the raw audio samples.
    ///
    /// \return Pointer to the audio samples (Int16 format).
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual Int16* GetSamples(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the number of channel in the audio buffer.
    ///
    /// \return Number of channels (e.g., 1 for mono, 2 for stereo).
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual UInt32 GetChannelCount(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the native handle of the underlying audio buffer.
    ///
    /// \return Pointer to the native audio buffer handle.
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void* GetNativeHandle(void) const = 0;
};

}   // namespace tkd
