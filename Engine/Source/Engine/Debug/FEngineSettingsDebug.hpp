///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Containers/FString.hpp>
#include <Engine/Debug/IDebugInterface.hpp>
#if TKD_ENGINE_CLIENT
    #include <imgui.h>
#endif

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd::debug
///////////////////////////////////////////////////////////////////////////////
namespace tkd::debug
{

#if TKD_ENGINE_CLIENT

///////////////////////////////////////////////////////////////////////////////
/// \brief Engine Settings Debug Interface
///
///////////////////////////////////////////////////////////////////////////////
class FEngineSettingsDebug : public IDebugInterface
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Show the debug interface
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Show(void) override;

private:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Show window settings tab
    ///
    ///////////////////////////////////////////////////////////////////////////
    void ShowWindowSettings(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Show network settings tab
    ///
    ///////////////////////////////////////////////////////////////////////////
    void ShowNetworkSettings(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Show logging settings tab
    ///
    ///////////////////////////////////////////////////////////////////////////
    void ShowLoggingSettings(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Show game settings tab
    ///
    ///////////////////////////////////////////////////////////////////////////
    void ShowGameSettings(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Show audio settings tab
    ///
    ///////////////////////////////////////////////////////////////////////////
    void ShowAudioSettings(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Show input settings tab
    ///
    ///////////////////////////////////////////////////////////////////////////
    void ShowInputSettings(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Show accessibility settings tab
    ///
    ///////////////////////////////////////////////////////////////////////////
    void ShowAccessibilitySettings(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Show action mappings
    ///
    ///////////////////////////////////////////////////////////////////////////
    void ShowActionMappings(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Show axis mappings
    ///
    ///////////////////////////////////////////////////////////////////////////
    void ShowAxisMappings(void);

private:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Helper function to display a boolean setting
    ///
    /// \param label The label for the setting
    /// \param value The boolean value to display
    ///
    ///////////////////////////////////////////////////////////////////////////
    static void DisplayBoolSetting(const char* label, bool value);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Helper function to display an integer setting
    ///
    /// \param label The label for the setting
    /// \param value The integer value to display
    ///
    ///////////////////////////////////////////////////////////////////////////
    static void DisplayIntSetting(const char* label, int value);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Helper function to display a float setting
    ///
    /// \param label The label for the setting
    /// \param value The float value to display
    ///
    ///////////////////////////////////////////////////////////////////////////
    static void DisplayFloatSetting(const char* label, float value);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Helper function to display a string setting
    ///
    /// \param label The label for the setting
    /// \param value The string value to display
    ///
    ///////////////////////////////////////////////////////////////////////////
    static void
        DisplayStringSetting(const char* label, const std::string& value);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get color for input type
    ///
    /// \param input The EInput enum value
    ///
    /// \return ImVec4 color for the input type
    ///
    ///////////////////////////////////////////////////////////////////////////
    static ImVec4 GetInputColor(EInput input);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get icon for input type
    ///
    /// \param input The EInput enum value
    ///
    /// \return Icon string for the input type
    ///
    ///////////////////////////////////////////////////////////////////////////
    static FString GetInputIcon(EInput input);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Convert EInput enum to string
    ///
    /// \param input The EInput enum value
    ///
    /// \return String representation of the EInput value
    ///
    ///////////////////////////////////////////////////////////////////////////
    static FString EInputToString(EInput input);
};

#endif

}   // namespace tkd::debug
