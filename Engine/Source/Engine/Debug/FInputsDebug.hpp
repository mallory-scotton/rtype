#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Containers/FString.hpp>
#include <Engine/Debug/IDebugInterface.hpp>
#include <vector>
#if TKD_ENGINE_CLIENT
    #include <imgui.h>
#endif

///////////////////////////////////////////////////////////////////////////////
// Forward Declarations
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{
class UInputAction;
class UInputAxis;
}   // namespace tkd

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd::debug
///////////////////////////////////////////////////////////////////////////////
namespace tkd::debug
{

#if TKD_ENGINE_CLIENT

///////////////////////////////////////////////////////////////////////////////
/// \brief Input System Debug Interface
///
///////////////////////////////////////////////////////////////////////////////
class FInputsDebug : public IDebugInterface
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Show the debug interface
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Show(const FEngineSettings& settings, UWorld* world) override;

private:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Display all input actions
    ///
    /// \param actions The list of input actions to display
    ///
    ///////////////////////////////////////////////////////////////////////////
    void ShowActions(const std::vector<UInputAction>& actions);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Display all input axes
    ///
    /// \param axes The list of input axes to display
    ///
    ///////////////////////////////////////////////////////////////////////////
    void ShowAxes(const std::vector<UInputAxis>& axes);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Display the state of an action
    ///
    /// \param action The action to display state for
    ///
    ///////////////////////////////////////////////////////////////////////////
    static void DisplayActionState(const UInputAction& action);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Display the current input for an action
    ///
    /// \param action The action to display current input for
    ///
    ///////////////////////////////////////////////////////////////////////////
    static void DisplayCurrentInput(const UInputAction& action);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Display bound inputs for an action
    ///
    /// \param inputs The list of inputs to display
    ///
    ///////////////////////////////////////////////////////////////////////////
    static void DisplayBoundInputs(const std::vector<EInput>& inputs);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Display bound inputs for an axis with their scales
    ///
    /// \param inputs The list of inputs with scales to display
    ///
    ///////////////////////////////////////////////////////////////////////////
    static void DisplayBoundAxisInputs(
        const std::vector<std::pair<EInput, float>>& inputs
    );

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Display numeric axis value with color coding
    ///
    /// \param value The axis value to display
    ///
    ///////////////////////////////////////////////////////////////////////////
    static void DisplayAxisValue(float value);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Display visual progress bar for axis value
    ///
    /// \param value The axis value to display
    ///
    ///////////////////////////////////////////////////////////////////////////
    static void DisplayAxisBar(float value);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get color for input type
    ///
    /// \param input The EInput enum value
    ///
    /// \return ImVec4 color for the input type
    ///
    ///////////////////////////////////////////////////////////////////////////
    static ImVec4 GetInputColor(EInput input);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get icon for input type
    ///
    /// \param input The EInput enum value
    ///
    /// \return Icon string for the input type
    ///
    ///////////////////////////////////////////////////////////////////////////
    static FString GetInputIcon(EInput input);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Convert EInput enum to string
    ///
    /// \param input The EInput enum value
    ///
    /// \return String representation of the EInput value
    ///
    ///////////////////////////////////////////////////////////////////////////
    static FString EInputToString(EInput input);
};

#endif

}   // namespace tkd::debug

