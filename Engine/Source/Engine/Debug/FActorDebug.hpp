///////////////////////////////////////////////////////////////////////////////
// Forward declarations
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{
class AActor;
class UActorComponent;
class UClass;
}   // namespace tkd

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd::debug
///////////////////////////////////////////////////////////////////////////////
namespace tkd::debug
{

#if TKD_ENGINE_CLIENT

///////////////////////////////////////////////////////////////////////////////
/// \brief Actor Debug Interface
///
///////////////////////////////////////////////////////////////////////////////
class FActorDebug : public IDebugInterface
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Show the debug interface
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Show(const FEngineSettings& settings, UWorld* world) override;

private:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Show the class hierarchy tab
    ///
    ///////////////////////////////////////////////////////////////////////////
    void ShowClassHierarchy(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Show the world view tab
    ///
    ///////////////////////////////////////////////////////////////////////////
    void ShowWorldView(UWorld* world);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Recursively display class hierarchy in tree view
    ///
    /// \param _class The class to display
    /// \param allClasses All registered classes
    ///
    ///////////////////////////////////////////////////////////////////////////
    void DisplayClassTree(
        UClass* _class, const std::vector<UClass*>& allClasses
    );

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Display properties for a class
    ///
    /// \param _class The class whose properties to display
    ///
    ///////////////////////////////////////////////////////////////////////////
    void DisplayClassProperties(UClass* _class);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Display functions for a class
    ///
    /// \param _class The class whose functions to display
    ///
    ///////////////////////////////////////////////////////////////////////////
    void DisplayClassFunctions(UClass* _class);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Display actor information
    ///
    /// \param actor The actor to display
    /// \param index The index of the actor in the world actor list
    ///
    ///////////////////////////////////////////////////////////////////////////
    void DisplayActorInfo(AActor* actor, SizeT index);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Display component information
    ///
    /// \param component The component to display
    ///
    ///////////////////////////////////////////////////////////////////////////
    void DisplayComponentInfo(UActorComponent* component);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Helper function to display a vector
    ///
    /// \param label The label for the vector
    /// \param vec The vector to display
    ///
    ///////////////////////////////////////////////////////////////////////////
    static void DisplayVector(const FVector3& vec);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Helper function to display a rotation as euler angles
    ///
    /// \param label The label for the rotation
    /// \param rotator The rotator to display
    ///
    ///////////////////////////////////////////////////////////////////////////
    static void DisplayRotation(const FRotator& rotator);
};

#endif

}   // namespace tkd::debug
