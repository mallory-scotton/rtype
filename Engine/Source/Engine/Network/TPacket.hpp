///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Network/IPacket.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief
///
///////////////////////////////////////////////////////////////////////////////
template <typename Derived>
class TPacket : public IPacket
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Static Class Member
    ///////////////////////////////////////////////////////////////////////////
    static inline UInt16 s_type = 0;   //<! Static packet type
    static inline bool s_typeInitialized =
        false;                         //<! true if the type is initialized

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the packet type
    ///
    /// \return packet type
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual UInt16 GetType(void) const override { return GetStaticType(); }

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the static packet type
    ///
    /// This function assigns a unique type ID to each derived packet class
    ///
    /// \return static packet type
    ///
    ///////////////////////////////////////////////////////////////////////////
    static UInt16 GetStaticType(void)
    {
        if (!s_typeInitialized)
        {
            s_type = IPacket::GetNextTypeId();
            s_typeInitialized = true;
        }
        return s_type;
    }
};

}   // namespace tkd
