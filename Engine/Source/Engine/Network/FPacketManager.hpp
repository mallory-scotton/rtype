#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Network/FPacketHeader.hpp>
#include <Engine/Network/IPacket.hpp>
#include <Engine/Network/TPacket.hpp>
#include <functional>
#include <memory>
#include <type_traits>
#include <unordered_map>
#include <vector>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief
///
///////////////////////////////////////////////////////////////////////////////
class FPacketManager
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Alias
    ///////////////////////////////////////////////////////////////////////////
    using Factory = std::function<std::unique_ptr<IPacket>()>;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    std::unordered_map<UInt16, Factory> m_factories;   //<! Packet factories
    UInt32 m_sequenceNumber = 0;   //<! Sequence number for packets

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Register a packet type
    ///
    ///////////////////////////////////////////////////////////////////////////
    template <typename T>
    void RegisterPacket(void)
    {
        static_assert(
            std::is_base_of_v<IPacket, T>, "T must derive from IPacket"
        );
        uint16_t typeId = T::GetStaticType();
        m_factories[typeId] = []() -> std::unique_ptr<IPacket>
        { return std::make_unique<T>(); };
    }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Serialize a packet into a byte vector
    ///
    /// \param packet The packet to serialize
    /// \param flags Flags for the packet
    ///
    /// \return Serialized byte vector
    ///
    ///////////////////////////////////////////////////////////////////////////
    std::vector<UInt8> SerializePacket(
        const IPacket& packet, EPacketFlags flags = EPacketFlags::None
    );

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Deserialize a packet from raw data
    ///
    /// \param data Raw data buffer
    /// \param size Size of the data buffer
    /// \param outHeader Output parameter for the packet header
    ///
    /// \return Unique pointer to the deserialized packet, or nullptr on
    /// failure
    ///
    ///////////////////////////////////////////////////////////////////////////
    std::unique_ptr<IPacket> DeserializePacket(
        const UInt8* data, SizeT size, FPacketHeader& outHeader
    );

private:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current timestamp
    ///
    /// \return current timestamp in milliseconds
    ///
    ///////////////////////////////////////////////////////////////////////////
    UInt32 GetCurrentTimestamp(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Calculate the checksum of the given data
    ///
    /// \param data The data to calculate the checksum for
    /// \param size The size of the data
    ///
    /// \return The calculated checksum
    ///
    ///////////////////////////////////////////////////////////////////////////
    UInt32 CalculateChecksum(const UInt8* data, SizeT size) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Validate the checksum of the given data
    ///
    /// \param data The data to validate
    /// \param size The size of the data
    /// \param expectedChecksum The expected checksum value
    ///
    /// \return True if the checksum is valid, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool ValidateChecksum(
        const UInt8* data, SizeT size, UInt32 expectedChecksum
    ) const;
};

}   // namespace tkd
