///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Network/FBinaryReader.hpp>
#include <Engine/Network/FBinaryWriter.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Interface for network packets
///
/// This interface defines the basic structure and functionality for network
/// packets, including serialization, deserialization, and size retrieval.
///
///////////////////////////////////////////////////////////////////////////////
class IPacket
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Virtual destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~IPacket() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the type of the packet
    ///
    /// \return packet type
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual UInt16 GetType(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Serialize the packet data into the writer
    ///
    /// \param writer Binary writer to serialize data into
    ///
    /// \return true if serialization was successful, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool Serialize(FBinaryWriter& writer) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Deserialize the packet data from the reader
    ///
    /// \param reader Binary reader to deserialize data from
    ///
    /// \return true if deserialization was successful, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual bool Deserialize(FBinaryReader& reader) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the size of the packet in bytes
    ///
    /// \return size of the packet in bytes
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual SizeT GetSize(void) const = 0;
};

}   // namespace tkd
