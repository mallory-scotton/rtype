namespace tkd::Packets
{

///////////////////////////////////////////////////////////////////////////////
bool Fragment::Serialize(FBinaryWriter& writer) const
{
    writer.Write(PackageID);
    writer.Write(SequenceID);
    writer.Write(FragmentCount);
    writer.Write(data);
    return true;
}

///////////////////////////////////////////////////////////////////////////////
bool Fragment::Deserialize(FBinaryReader& reader)
{
    return reader.Read(PackageID) && reader.Read(SequenceID) &&
           reader.Read(FragmentCount) && reader.Read(data);
}

///////////////////////////////////////////////////////////////////////////////
SizeT Fragment::GetSize(void) const
{
    return sizeof(SizeT) + data.size() + sizeof(PackageID) +
           sizeof(SequenceID) + sizeof(FragmentCount);
}

}   // namespace tkd::Packets
