#include <Engine/Network/Packets/Acknowledgment.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd::Packets
///////////////////////////////////////////////////////////////////////////////
namespace tkd::Packets
{

///////////////////////////////////////////////////////////////////////////////
bool Acknowledgment::Serialize(FBinaryWriter& writer) const
{
    writer.Write(ackedSequenceNumber);
    return true;
}

///////////////////////////////////////////////////////////////////////////////
bool Acknowledgment::Deserialize(FBinaryReader& reader)
{
    return reader.Read(ackedSequenceNumber);
}

///////////////////////////////////////////////////////////////////////////////
SizeT Acknowledgment::GetSize(void) const
{
    return sizeof(ackedSequenceNumber);
}

}   // namespace tkd::Packets
