///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Network/Packets/HeartBeat.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd::Packets
///////////////////////////////////////////////////////////////////////////////
namespace tkd::Packets
{

///////////////////////////////////////////////////////////////////////////////
bool HeartBeat::Serialize(FBinaryWriter& writer) const
{
    writer.Write(id);
    writer.Write(timestamp);
    return true;
}

///////////////////////////////////////////////////////////////////////////////
bool HeartBeat::Deserialize(FBinaryReader& reader)
{
    return reader.Read(id) && reader.Read(timestamp);
}

///////////////////////////////////////////////////////////////////////////////
SizeT HeartBeat::GetSize(void) const { return sizeof(id) + sizeof(timestamp); }

}   // namespace tkd::Packets
