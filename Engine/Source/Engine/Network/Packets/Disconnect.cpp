///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Network/Packets/Disconnect.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd::Packets
///////////////////////////////////////////////////////////////////////////////
namespace tkd::Packets
{

///////////////////////////////////////////////////////////////////////////////
bool Disconnect::Serialize(FBinaryWriter& writer) const
{
    writer.Write(clientID);
    writer.Write(reason);
    return true;
}

///////////////////////////////////////////////////////////////////////////////
bool Disconnect::Deserialize(FBinaryReader& reader)
{
    return reader.Read(clientID) && reader.Read(reason);
}

///////////////////////////////////////////////////////////////////////////////
SizeT Disconnect::GetSize(void) const
{
    return sizeof(clientID) + sizeof(reason);
}

}   // namespace tkd::Packets
