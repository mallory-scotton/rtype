#include <Engine/Network/Packets/FragmentAcknowledgment.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd::Packets
///////////////////////////////////////////////////////////////////////////////
namespace tkd::Packets
{

///////////////////////////////////////////////////////////////////////////////
bool FragmentAcknowledgment::Serialize(FBinaryWriter& writer) const
{
    writer.Write(PackageID);
    writer.Write(FragmentID);
    return true;
}

///////////////////////////////////////////////////////////////////////////////
bool FragmentAcknowledgment::Deserialize(FBinaryReader& reader)
{
    return reader.Read(PackageID) && reader.Read(FragmentID);
}

///////////////////////////////////////////////////////////////////////////////
SizeT FragmentAcknowledgment::GetSize(void) const
{
    return sizeof(PackageID) + sizeof(FragmentID);
}

}   // namespace tkd::Packets

