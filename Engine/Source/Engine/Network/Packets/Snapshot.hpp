namespace tkd::Packets
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Snapshot packet class for synchronizing game state
///
///////////////////////////////////////////////////////////////////////////////
class Snapshot : public TPacket<Snapshot>
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Structure representing the state of an actor
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct ActorState
    {
        FString className;       //<! Class name of the actor
        UUID id;                 //<! Unique identifier for the actor
        FTransform transform;    //<! Transform of the actor
        std::unordered_map<FString, std::vector<Byte>>
            properties;          //<! Serialized properties
        UInt32 owningClientID;   //<! ID of the owning client
    };

public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    UInt32 snapshotID = 0;            //<! Unique ID for the snapshot
    std::vector<ActorState> actors;   //<! List of actor states in the snapshot

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    Snapshot(void) = default;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor to create a snapshot from the world state
    ///
    /// \param world The world to take the snapshot from
    ///
    ///////////////////////////////////////////////////////////////////////////
    Snapshot(const UWorld& world);

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Setup the snapshot from the world state
    ///
    /// \param world The world to take the snapshot from
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetupFromWorld(const UWorld& world);

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Serialize the packet data into the writer
    ///
    /// \param writer Binary writer to serialize data into
    ///
    /// \return true if serialization was successful, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool Serialize(FBinaryWriter& writer) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Deserialize the packet data from the reader
    ///
    /// \param reader Binary reader to deserialize data from
    ///
    /// \return true if deserialization was successful, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool Deserialize(FBinaryReader& reader) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the size of the packet in bytes
    ///
    /// \return size of the packet in bytes
    ///
    ///////////////////////////////////////////////////////////////////////////
    SizeT GetSize(void) const override;
};

}   // namespace tkd::Packets
