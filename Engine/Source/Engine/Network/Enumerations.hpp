namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Replication types for networked actors
///
///////////////////////////////////////////////////////////////////////////////
enum class EReplicationType : UInt8
{
    None = 0,
    ReplicatedToAll = 1,     //<! Replicate to all clients
    ReplicatedToOwner = 2,   //<! Only to owning client
    SimulatedOnClients = 4   //<! Allow client-side prediction
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Network roles for actors
///
///////////////////////////////////////////////////////////////////////////////
enum class ENetRole : UInt8
{
    None,
    SimulatedProxy,    //<! Non-authoritative client
    AutonomousProxy,   //<! Owning client (can predict)
    Authority          //<! Server
};

///////////////////////////////////////////////////////////////////////////////
/// \brief RPC types for remote procedure calls
///
///////////////////////////////////////////////////////////////////////////////
enum class ERPCType : UInt8
{
    Server,     //<! Client->Server, requires validation
    Client,     //<! Server->Client
    Multicast   //<! Server->All Clients
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Data structure for property replication
///
///////////////////////////////////////////////////////////////////////////////
struct FReplicationData
{
    UInt32 actorID;            //>! The ID of the actor
    UInt32 timestamp;          //<! The timestamp of the replication
    std::vector<UInt8> data;   //<! The serialized property data
};

}   // namespace tkd
