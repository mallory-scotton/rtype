namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Interface for tickable objects
///
/// This interface defines the methods that must be implemented by any
/// object that wants to be updated on a regular basis (i.e., "ticked").
///
///////////////////////////////////////////////////////////////////////////////
class ITickable
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    ITickable(void) = default;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Virtual destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~ITickable() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is first created
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void BeginPlay(void) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Ticks the object
    ///
    /// \param deltaTime The time elapsed since the last tick
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Tick(Float32 deltaTime) = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is being destroyed
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void EndPlay(void) = 0;
};

}   // namespace tkd
