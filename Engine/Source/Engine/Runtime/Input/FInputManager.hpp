///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Containers.hpp>
#include <Engine/Renderer/Interfaces/IWindow.hpp>
#include <Engine/Runtime/Input/UInputAction.hpp>
#include <Engine/Runtime/Input/UInputAxis.hpp>
#include <optional>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Singleton class to manage input actions and their associated inputs.
///
///////////////////////////////////////////////////////////////////////////////
class FInputManager
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Members
    ///////////////////////////////////////////////////////////////////////////
    std::vector<UInputAction> m_actions;   //<! List of input actions.
    std::vector<UInputAxis> m_axes;        //<! List of input axes.
    bool m_invertY = false;                //<! Invert Y-axis flag.
    bool m_enableGamepad = true;           //<! Enable gamepad input flag.
    bool m_initialized = false;            //<! Initialization flag.

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    FInputManager(void) = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Initialize the input manager with engine settings
    ///
    /// \param settings The engine settings to use for initialization
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Initialize(const FEngineSettings& settings);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the input manager is initialized
    ///
    /// \return True if initialized, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool IsInitialized(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if Y-axis inversion is enabled
    ///
    /// \return True if Y-axis is inverted, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool IsInvertY(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if Y-axis inversion is enabled
    ///
    /// \return True if Y-axis is inverted, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool IsGamepadEnabled(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the list of input actions
    ///
    /// \return Constant reference to the vector of input actions
    ///
    ///////////////////////////////////////////////////////////////////////////
    const std::vector<UInputAction>& GetActions(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Find an input action by name
    ///
    /// \param actionName The name of the input action to find
    ///
    /// \return An optional containing the found input action, or an empty
    /// optional if not found
    ///
    ///////////////////////////////////////////////////////////////////////////
    const UInputAction* GetAction(const FString& actionName) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the list of input axes
    ///
    /// \return Constant reference to the vector of input axes
    ///
    ///////////////////////////////////////////////////////////////////////////
    const std::vector<UInputAxis>& GetAxes(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Find an input axis by name
    ///
    /// \param axisName The name of the input axis to find
    ///
    /// \return An optional containing the found input axis, or an empty
    /// optional if not found
    ///
    ///////////////////////////////////////////////////////////////////////////
    const UInputAxis* GetAxis(const FString& axisName) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current value of an input axis
    ///
    /// \param axisName The name of the input axis
    ///
    /// \return The current value of the axis, or 0.0f if not found
    ///
    ///////////////////////////////////////////////////////////////////////////
    Float32 GetAxisValue(const FString& axisName) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set whether to invert the Y-axis
    ///
    /// \param invert True to invert Y-axis, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetInvertY(bool invert);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set whether gamepad input is enabled
    ///
    /// \param enable True to enable gamepad input, false to disable
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetGamepadEnabled(bool enable);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Update the input manager state
    ///
    /// \param window Pointer to the window for context (if needed)
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Update(IWindow* window);
};

}   // namespace tkd
