///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Containers/FString.hpp>
#include <Engine/Core/Utils/EventEmitter.hpp>
#include <utility>
#include <vector>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
// Forward Declarations
///////////////////////////////////////////////////////////////////////////////
class UInputAxis;

///////////////////////////////////////////////////////////////////////////////
/// \brief
///
///////////////////////////////////////////////////////////////////////////////
template <>
struct TEvents<UInputAxis>
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Changed event structure
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct Changed
    {
        float value;    //<! The new value of the axis.
        float delta;    //<! The change in value since the last event.
        EInput input;   //<! The input that triggered the event.
    };

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Reset event structure
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct Reset
    {};

public:
    using All = std::tuple<Changed, Reset>;
};

///////////////////////////////////////////////////////////////////////////////
/// \brief UInputAxis class for managing input axes in the engine.
///
///////////////////////////////////////////////////////////////////////////////
class UInputAxis : public TEventEmitter<TEvents<UInputAxis>::All>
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FString m_name;   //<! Name of the input action.
    std::vector<std::pair<EInput, float>>
        m_inputs;     //<! List of associated inputs.
    float m_scale;    //<! Current scale of the axis.

public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Aliases
    ///////////////////////////////////////////////////////////////////////////
    using Events = TEvents<UInputAxis>;   //<! Alias for event types.
    using Input = std::pair<EInput, float>;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor for UInputAxis.
    ///
    /// \param name Name of the input action.
    /// \param inputs List of associated inputs.
    ///
    ///////////////////////////////////////////////////////////////////////////
    UInputAxis(const FString& name, const std::vector<Input>& inputs);

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the name of the input action.
    ///
    /// \return The name of the input action.
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FString& GetName(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the inputs associated with this action.
    ///
    /// \return A constant reference to the vector of associated inputs.
    ///
    ///////////////////////////////////////////////////////////////////////////
    const std::vector<Input>& GetInputs(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Bind an additional input to this axis.
    ///
    /// \param input The input to bind.
    /// \param scale The scale factor for the input.
    ///
    /// \return True if the input was successfully bound, false if it was
    /// already bound.
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool Bind(EInput input, float scale);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Unbind an input from this axis.
    ///
    /// \param input The input to unbind.
    ///
    /// \return True if the input was successfully unbound, false if it was
    /// not found.
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool Unbind(EInput input);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Clear all input bindings from this axis.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void ClearBindings(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Simulate moving the axis by a certain value.
    ///
    /// \param input The input causing the movement.
    /// \param factor The factor by which to move the axis [0, 1].
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Move(EInput input, float factor = 1.0f);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Reset the axis to its default state.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Reset(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current scale of the axis.
    ///
    /// \return The current scale of the axis.
    ///
    ///////////////////////////////////////////////////////////////////////////
    float GetScale(void) const;
};

}   // namespace tkd
