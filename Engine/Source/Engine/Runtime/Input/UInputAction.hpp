#include <Engine/Core/Utils/EventEmitter.hpp>
#include <vector>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
// Forward Declarations
///////////////////////////////////////////////////////////////////////////////
class UInputAction;

///////////////////////////////////////////////////////////////////////////////
/// \brief Specialization of TEvents for UInputAction to define its event
/// types.
///
///////////////////////////////////////////////////////////////////////////////
template <>
struct TEvents<UInputAction>
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Pressed event structure
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct Pressed
    {
        EInput input;   //<! The input that was pressed.
    };

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Released event structure
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct Released
    {
        EInput input;   //<! The input that was pressed.
    };

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Held event structure
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct Held
    {
        EInput input;   //<! The input that was pressed.
    };

public:
    using All = std::tuple<Pressed, Released, Held>;
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Class representing an input action, which can be associated with
/// multiple input types (e.g., keyboard keys, mouse buttons, gamepad buttons).
///
///////////////////////////////////////////////////////////////////////////////
class UInputAction : public TEventEmitter<TEvents<UInputAction>::All>
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FString m_name;                 //<! Name of the input action.
    std::vector<EInput> m_inputs;   //<! List of associated inputs.

public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Aliases
    ///////////////////////////////////////////////////////////////////////////
    using Events = TEvents<UInputAction>;   //<! Alias for event types.

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor for UInputAction.
    ///
    /// \param name Name of the input action.
    /// \param inputs List of associated inputs.
    ///
    ///////////////////////////////////////////////////////////////////////////
    UInputAction(const FString& name, const std::vector<EInput>& inputs);

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Simulate pressing an input associated with this action.
    ///
    /// \param input The input to press.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Press(EInput input);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Simulate releasing an input associated with this action.
    ///
    /// \param input The input to release.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Release(EInput input);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Simulate holding an input associated with this action.
    ///
    /// \param input The input to hold.
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Hold(EInput input);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the name of the input action.
    ///
    /// \return The name of the input action.
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FString& GetName(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the inputs associated with this action.
    ///
    /// \return A constant reference to the vector of associated inputs.
    ///
    ///////////////////////////////////////////////////////////////////////////
    const std::vector<EInput>& GetInputs(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Bind an additional input to this action.
    ///
    /// \param input The input to bind.
    ///
    /// \return True if the input was successfully bound, false if it was
    /// already bound.
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool Bind(EInput input);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Unbind an input from this action.
    ///
    /// \param input The input to unbind.
    ///
    /// \return True if the input was successfully unbound, false if it was
    /// not found.
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool Unbind(EInput input);
};

}   // namespace tkd
