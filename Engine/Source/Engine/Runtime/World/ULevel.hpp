#include <Engine/Assets/UAsset.hpp>
#include <Engine/Config.hpp>
#include <Engine/Core.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{
///////////////////////////////////////////////////////////////////////////////
// Forward Declarations
///////////////////////////////////////////////////////////////////////////////
class UWorld;

///////////////////////////////////////////////////////////////////////////////
// Class ULevel
///////////////////////////////////////////////////////////////////////////////
class ULevel
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct PropertyEntry
    {
        FString name;   ///< Property name
        SizeT size;     ///< Property size (e.g., int, float, string)
        std::vector<Byte> value;   ///< Property value as byte array
    };

    ///////////////////////////////////////////////////////////////////////////
    /// \brief
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct ActorEntry
    {
        FString class_name;                  ///< Actor class name
        FString name;                        ///< Actor name
        bool isActive;                       ///< Whether the actor is active
        FVector3 position;                   ///< Actor position
        FRotator rotation;                   ///< Actor rotation
        FVector3 scale;                      ///< Actor scale
        TVector<PropertyEntry> properties;   ///< List of properties
    };

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    // AGameMode m_gameMode;               ///< Pointer to the game mode
    TVector<ActorEntry> m_actorEntries;   ///< List of actor entries
    FString m_levelName;                  ///< Name of the level

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    ULevel() = default;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~ULevel() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief
    ///
    ///////////////////////////////////////////////////////////////////////////
    // const AGameMode& GetGameMode(void) const { return m_gameMode; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief
    ///
    ///////////////////////////////////////////////////////////////////////////
    // void SetGameMode(const AGameMode& gameMode) { m_gameMode = gameMode; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief
    ///
    ///////////////////////////////////////////////////////////////////////////
    const TVector<ActorEntry>& GetActorEntries(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetActorEntries(const TVector<ActorEntry>& actors);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the level name
    ///
    /// \return The name of the level
    ///
    ///////////////////////////////////////////////////////////////////////////
    FString GetLevelName(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the level name
    ///
    /// \param name The new name of the level
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetLevelName(const FString& name);

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Load level from UAsset
    ///
    /// \param asset The UAsset object containing level data
    ///
    ///////////////////////////////////////////////////////////////////////////
    static ULevel LoadLevelFromAsset(UAsset& asset);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Load level from file
    ///
    /// \param levelPath The file path to the level data
    ///
    ///////////////////////////////////////////////////////////////////////////
    static ULevel LoadLevelFromFile(const FilePath& levelPath);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Load level from UWorld
    ///
    /// \param world The UWorld object containing level data
    ///
    /// \return The loaded ULevel object
    ///
    ///////////////////////////////////////////////////////////////////////////
    static ULevel LoadLevelFromWorld(UWorld& world);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Unload the current level and clear data
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool UnLoadLevel(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Save the current level to a file
    ///
    /// \param levelPath The file path to save the level data
    ///
    /// \return True if the level was saved successfully, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool SaveToFile(const FilePath& levelPath);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Save the current level to a UAsset
    ///
    /// \param asset The UAsset object to save the level data
    ///
    /// \return True if the level was saved successfully, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool SaveToAsset(UAsset& asset);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Save the current world to a file
    ///
    /// \param world The UWorld object containing the level to save
    /// \param levelPath The file path to save the level data
    ///
    /// \return True if the world was saved successfully, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool SaveWorldToFile(UWorld& world, const FilePath& levelPath);

private:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Helper to parse level data from binary format
    ///
    /// \param data The binary data of the level
    ///
    /// \return True if parsing was successful, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool ParseLevelData(const std::vector<Byte>& data);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Helper to serialize level data to binary format
    ///
    /// \return The serialized binary data of the level
    ///
    ///////////////////////////////////////////////////////////////////////////
    std::vector<Byte> SerializeLevelData(void) const;
};

}   // namespace tkd
