ACamera::ACamera(const FString& name)
    : AActor(name)
    , ViewTransform(*this, "ViewTransform", FTransform::Identity)
    , FieldOfView(*this, "FieldOfView", 90.0f)
    , AspectRatio(*this, "AspectRatio", 16.0f / 9.0f)
    , NearClipPlane(*this, "NearClipPlane", 0.1f)
    , FarClipPlane(*this, "FarClipPlane", 1000.0f)
{
    SetTransformReplicated(false);
}

