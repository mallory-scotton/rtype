///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Box collision component class
///
///////////////////////////////////////////////////////////////////////////////
class UBoxCollisionComponent : public UCollisionComponent
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FVector3f m_boxExtent;             //<! The extent of the box collision
    FTransform m_localTransform;       //<! The local transform
    std::vector<FVertex> m_vertices;   //<! The vertices of the box

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    UBoxCollisionComponent(const FString& name = "BoxCollisionComponent");

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the box extent
    ///
    /// \return The box extent
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FVector3f& GetBoxExtent(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the box extent
    ///
    /// \param extent The new box extent
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetBoxExtent(const FVector3f& extent);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the local transform
    ///
    /// \return The local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FTransform& GetLocalTransform(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the local transform
    ///
    /// \param transform The new local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetLocalTransform(const FTransform& transform);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the box using the provided renderer if hidden in game is
    /// false
    ///
    /// \param renderer The renderer to use for drawing
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the local bounding box of the component
    ///
    /// \return The local oriented bounding box
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FOBB GetLocalBoundingBox(void) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the world bounding box of the component
    ///
    /// \return The world oriented bounding box
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FOBB GetWorldBoundingBox(void) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the world AABB for spatial partitioning
    ///
    /// \return The world axis-aligned bounding box
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FAABB GetWorldAABB(void) const override;
};

}   // namespace tkd
