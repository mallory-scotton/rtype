///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Runtime/Components/UCylinderComponent.hpp>
#include <Engine/Runtime/Actor/AActor.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
UCylinderComponent::UCylinderComponent(const FString& name)
    : UActorComponent(name)
    , m_cylinder()
    , m_localTransform(FTransform::Identity)
{}

///////////////////////////////////////////////////////////////////////////////
UCylinderPrimitive& UCylinderComponent::GetCylinder(void)
{
    return m_cylinder;
}

///////////////////////////////////////////////////////////////////////////////
const UCylinderPrimitive& UCylinderComponent::GetCylinder(void) const
{
    return m_cylinder;
}

///////////////////////////////////////////////////////////////////////////////
const FTransform& UCylinderComponent::GetLocalTransform(void) const
{
    return m_localTransform;
}

///////////////////////////////////////////////////////////////////////////////
void UCylinderComponent::SetLocalTransform(const FTransform& transform)
{
    m_localTransform = transform;
}

///////////////////////////////////////////////////////////////////////////////
void UCylinderComponent::Render(IRenderer& renderer) const
{
    if (IsHiddenInGame()) { return; }

    // Update the cylinder transform with owner + local transform
    FTransform ownerTransform = GetOwner()->GetTransform();
    m_cylinder.SetTransform(ownerTransform * m_localTransform);

    FRenderStates states;
    m_cylinder.Draw(renderer, states);
}

}   // namespace tkd
