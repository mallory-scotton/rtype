///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Primitives/UCapsulePrimitive.hpp>
#include <Engine/Runtime/Components/UActorComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief A component that represents a 3D capsule primitive in the game world
///
///////////////////////////////////////////////////////////////////////////////
class UCapsuleComponent : public UActorComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UActorComponent;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    mutable UCapsulePrimitive m_capsule;   //<! The capsule primitive
    FTransform m_localTransform;   //<! The local transform of the capsule

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ////////////////////////////////////////////////////////////////////////////
    UCapsuleComponent(const FString& name = "CapsuleComponent");

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the capsule primitive associated with this component
    ///
    /// \return Reference to the capsule
    ///
    ///////////////////////////////////////////////////////////////////////////
    UCapsulePrimitive& GetCapsule(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the capsule primitive associated with this component
    ///
    /// \return Constant reference to the capsule
    ///
    ///////////////////////////////////////////////////////////////////////////
    const UCapsulePrimitive& GetCapsule(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the local transform of the capsule
    ///
    /// \return Constant reference to the local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FTransform& GetLocalTransform(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the local transform of the capsule
    ///
    /// \param transform The new local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetLocalTransform(const FTransform& transform);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the capsule using the provided renderer
    ///
    /// \param renderer The renderer to use for drawing
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;
};

}   // namespace tkd
