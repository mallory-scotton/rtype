///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Primitives/UPyramidPrimitive.hpp>
#include <Engine/Runtime/Components/UActorComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief A component that represents a 3D pyramid primitive in the game world
///
///////////////////////////////////////////////////////////////////////////////
class UPyramidComponent : public UActorComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UActorComponent;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    mutable UPyramidPrimitive m_pyramid;   //<! The pyramid primitive
    FTransform m_localTransform;   //<! The local transform of the pyramid

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ////////////////////////////////////////////////////////////////////////////
    UPyramidComponent(const FString& name = "PyramidComponent");

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the pyramid primitive associated with this component
    ///
    /// \return Reference to the pyramid
    ///
    ///////////////////////////////////////////////////////////////////////////
    UPyramidPrimitive& GetPyramid(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the pyramid primitive associated with this component
    ///
    /// \return Constant reference to the pyramid
    ///
    ///////////////////////////////////////////////////////////////////////////
    const UPyramidPrimitive& GetPyramid(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the local transform of the pyramid
    ///
    /// \return Constant reference to the local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FTransform& GetLocalTransform(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the local transform of the pyramid
    ///
    /// \param transform The new local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetLocalTransform(const FTransform& transform);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the pyramid using the provided renderer
    ///
    /// \param renderer The renderer to use for drawing
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;
};

}   // namespace tkd
