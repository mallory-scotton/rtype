///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Runtime/Components/UTorusComponent.hpp>
#include <Engine/Runtime/Actor/AActor.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
UTorusComponent::UTorusComponent(const FString& name)
    : UActorComponent(name)
    , m_torus()
    , m_localTransform(FTransform::Identity)
{}

///////////////////////////////////////////////////////////////////////////////
UTorusPrimitive& UTorusComponent::GetTorus(void) { return m_torus; }

///////////////////////////////////////////////////////////////////////////////
const UTorusPrimitive& UTorusComponent::GetTorus(void) const
{
    return m_torus;
}

///////////////////////////////////////////////////////////////////////////////
const FTransform& UTorusComponent::GetLocalTransform(void) const
{
    return m_localTransform;
}

///////////////////////////////////////////////////////////////////////////////
void UTorusComponent::SetLocalTransform(const FTransform& transform)
{
    m_localTransform = transform;
}

///////////////////////////////////////////////////////////////////////////////
void UTorusComponent::Render(IRenderer& renderer) const
{
    if (IsHiddenInGame()) { return; }

    // Update the torus transform with owner + local transform
    FTransform ownerTransform = GetOwner()->GetTransform();
    m_torus.SetTransform(ownerTransform * m_localTransform);

    FRenderStates states;
    m_torus.Draw(renderer, states);
}

}   // namespace tkd
