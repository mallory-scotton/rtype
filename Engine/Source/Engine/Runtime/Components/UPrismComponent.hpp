///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Primitives/UPrismPrimitive.hpp>
#include <Engine/Runtime/Components/UActorComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief A component that represents a 3D prism primitive in the game world
///
///////////////////////////////////////////////////////////////////////////////
class UPrismComponent : public UActorComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UActorComponent;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    mutable UPrismPrimitive m_prism;   //<! The prism primitive
    FTransform m_localTransform;       //<! The local transform of the prism

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ////////////////////////////////////////////////////////////////////////////
    UPrismComponent(const FString& name = "PrismComponent");

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the prism primitive associated with this component
    ///
    /// \return Reference to the prism
    ///
    ///////////////////////////////////////////////////////////////////////////
    UPrismPrimitive& GetPrism(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the prism primitive associated with this component
    ///
    /// \return Constant reference to the prism
    ///
    ///////////////////////////////////////////////////////////////////////////
    const UPrismPrimitive& GetPrism(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the local transform of the prism
    ///
    /// \return Constant reference to the local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FTransform& GetLocalTransform(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the local transform of the prism
    ///
    /// \param transform The new local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetLocalTransform(const FTransform& transform);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the prism using the provided renderer
    ///
    /// \param renderer The renderer to use for drawing
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;
};

}   // namespace tkd
