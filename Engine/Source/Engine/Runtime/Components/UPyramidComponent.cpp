///////////////////////////////////////////////////////////////////////////////
#include <Engine/Runtime/Components/UPyramidComponent.hpp>
#include <Engine/Runtime/Actor/AActor.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
UPyramidComponent::UPyramidComponent(const FString& name)
    : UActorComponent(name)
    , m_pyramid()
    , m_localTransform(FTransform::Identity)
{}

///////////////////////////////////////////////////////////////////////////////
UPyramidPrimitive& UPyramidComponent::GetPyramid(void) { return m_pyramid; }

///////////////////////////////////////////////////////////////////////////////
const UPyramidPrimitive& UPyramidComponent::GetPyramid(void) const
{
    return m_pyramid;
}

///////////////////////////////////////////////////////////////////////////////
const FTransform& UPyramidComponent::GetLocalTransform(void) const
{
    return m_localTransform;
}

///////////////////////////////////////////////////////////////////////////////
void UPyramidComponent::SetLocalTransform(const FTransform& transform)
{
    m_localTransform = transform;
}

///////////////////////////////////////////////////////////////////////////////
void UPyramidComponent::Render(IRenderer& renderer) const
{
    if (IsHiddenInGame()) { return; }

    // Update the pyramid transform with owner + local transform
    FTransform ownerTransform = GetOwner()->GetTransform();
    m_pyramid.SetTransform(ownerTransform * m_localTransform);

    FRenderStates states;
    m_pyramid.Draw(renderer, states);
}

}   // namespace tkd
