///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Primitives/UCubePrimitive.hpp>
#include <Engine/Runtime/Components/UActorComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief A component that represents a 3D cube primitive in the game world
///
///////////////////////////////////////////////////////////////////////////////
class UCubeComponent : public UActorComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UActorComponent;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    mutable UCubePrimitive m_cube;   //<! The cube primitive
    FTransform m_localTransform;     //<! The local transform of the cube

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ////////////////////////////////////////////////////////////////////////////
    UCubeComponent(const FString& name = "CubeComponent");

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the cube primitive associated with this component
    ///
    /// \return Reference to the cube
    ///
    ///////////////////////////////////////////////////////////////////////////
    UCubePrimitive& GetCube(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the cube primitive associated with this component
    ///
    /// \return Constant reference to the cube
    ///
    ///////////////////////////////////////////////////////////////////////////
    const UCubePrimitive& GetCube(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the local transform of the cube
    ///
    /// \return Constant reference to the local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FTransform& GetLocalTransform(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the local transform of the cube
    ///
    /// \param transform The new local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetLocalTransform(const FTransform& transform);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the texture of the cube
    ///
    /// \param texture The texture to apply to the cube
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetTexture(ITexture* texture);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the texture of the cube
    ///
    /// \return Pointer to the texture
    ///
    ///////////////////////////////////////////////////////////////////////////
    ITexture* GetTexture(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the cube using the provided renderer
    ///
    /// \param renderer The renderer to use for drawing
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;
};

}   // namespace tkd
