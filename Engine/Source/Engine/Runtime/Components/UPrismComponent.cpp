///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Runtime/Components/UPrismComponent.hpp>
#include <Engine/Runtime/Actor/AActor.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
UPrismComponent::UPrismComponent(const FString& name)
    : UActorComponent(name)
    , m_prism()
    , m_localTransform(FTransform::Identity)
{}

///////////////////////////////////////////////////////////////////////////////
UPrismPrimitive& UPrismComponent::GetPrism(void) { return m_prism; }

///////////////////////////////////////////////////////////////////////////////
const UPrismPrimitive& UPrismComponent::GetPrism(void) const
{
    return m_prism;
}

///////////////////////////////////////////////////////////////////////////////
const FTransform& UPrismComponent::GetLocalTransform(void) const
{
    return m_localTransform;
}

///////////////////////////////////////////////////////////////////////////////
void UPrismComponent::SetLocalTransform(const FTransform& transform)
{
    m_localTransform = transform;
}

///////////////////////////////////////////////////////////////////////////////
void UPrismComponent::Render(IRenderer& renderer) const
{
    if (IsHiddenInGame()) { return; }

    // Update the prism transform with owner + local transform
    FTransform ownerTransform = GetOwner()->GetTransform();
    m_prism.SetTransform(ownerTransform * m_localTransform);

    FRenderStates states;
    m_prism.Draw(renderer, states);
}

}   // namespace tkd
