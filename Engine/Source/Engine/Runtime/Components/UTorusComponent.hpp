///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Primitives/UTorusPrimitive.hpp>
#include <Engine/Runtime/Components/UActorComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief A component that represents a 3D torus primitive in the game world
///
///////////////////////////////////////////////////////////////////////////////
class UTorusComponent : public UActorComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UActorComponent;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    mutable UTorusPrimitive m_torus;   //<! The torus primitive
    FTransform m_localTransform;       //<! The local transform of the torus

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ////////////////////////////////////////////////////////////////////////////
    UTorusComponent(const FString& name = "TorusComponent");

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the torus primitive associated with this component
    ///
    /// \return Reference to the torus
    ///
    ///////////////////////////////////////////////////////////////////////////
    UTorusPrimitive& GetTorus(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the torus primitive associated with this component
    ///
    /// \return Constant reference to the torus
    ///
    ///////////////////////////////////////////////////////////////////////////
    const UTorusPrimitive& GetTorus(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the local transform of the torus
    ///
    /// \return Constant reference to the local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FTransform& GetLocalTransform(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the local transform of the torus
    ///
    /// \param transform The new local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetLocalTransform(const FTransform& transform);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the torus using the provided renderer
    ///
    /// \param renderer The renderer to use for drawing
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;
};

}   // namespace tkd
