namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
// Forward declarations
///////////////////////////////////////////////////////////////////////////////
class UAnimatedSpriteComponent;

///////////////////////////////////////////////////////////////////////////////
/// \brief Event definitions for UAnimatedSpriteComponent
///
///////////////////////////////////////////////////////////////////////////////
template <>
class TEvents<UAnimatedSpriteComponent>
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Event emitted when an animation begins
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct AnimationBegin
    {
        FString name;   //<! Name of the completed animation
    };

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Event emitted when an animation loops
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct AnimationLoop
    {
        FString name;   //<! Name of the completed animation
    };

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Event emitted when an animation completes
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct AnimationComplete
    {
        FString name;   //<! Name of the completed animation
    };

public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    using All = std::tuple<AnimationBegin, AnimationLoop, AnimationComplete>;
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Component that handles sprite animation with multiple animation
/// sequences
///
///////////////////////////////////////////////////////////////////////////////
class UAnimatedSpriteComponent
    : public UActorComponent
    , public TEventEmitter<TEvents<UAnimatedSpriteComponent>::All>
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    USprite m_sprite;             //<! The sprite being animated
    TMap<FString, FAnimation2D>
        m_animations;             //<! Map of animation names to animations
    FString m_currentAnimation;   //<! Name of the current animation
    SizeT m_currentFrame;         //<! Index of the current frame
    Float32 m_elapsedTime;        //<! Time elapsed since last frame change
    Float32 m_playbackSpeed;      //<! Speed multiplier for playback
    bool m_isPaused;              //<! Whether the animation is paused

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor
    ///
    /// \param name The name of the component
    ///
    ///////////////////////////////////////////////////////////////////////////
    UAnimatedSpriteComponent(const FString& name = "AnimatedSpriteComponent");
};

}   // namespace tkd
