#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Primitives/UPlanePrimitive.hpp>
#include <Engine/Runtime/Components/UActorComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief A component that represents a 3D plane primitive in the game world
///
///////////////////////////////////////////////////////////////////////////////
class UPlaneComponent : public UActorComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UActorComponent;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    mutable UPlanePrimitive m_plane;   //<! The plane primitive
    FTransform m_localTransform;       //<! The local transform of the plane

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ////////////////////////////////////////////////////////////////////////////
    UPlaneComponent(const FString& name = "PlaneComponent");

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the plane primitive associated with this component
    ///
    /// \return Reference to the plane
    ///
    ///////////////////////////////////////////////////////////////////////////
    UPlanePrimitive& GetPlane(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the plane primitive associated with this component
    ///
    /// \return Constant reference to the plane
    ///
    ///////////////////////////////////////////////////////////////////////////
    const UPlanePrimitive& GetPlane(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the local transform of the plane
    ///
    /// \return Constant reference to the local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FTransform& GetLocalTransform(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the local transform of the plane
    ///
    /// \param transform The new local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetLocalTransform(const FTransform& transform);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the plane using the provided renderer
    ///
    /// \param renderer The renderer to use for drawing
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;
};

}   // namespace tkd
