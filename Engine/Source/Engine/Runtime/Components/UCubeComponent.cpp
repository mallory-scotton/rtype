///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Runtime/Components/UCubeComponent.hpp>
#include <Engine/Runtime/Actor/AActor.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
UCubeComponent::UCubeComponent(const FString& name)
    : UActorComponent(name)
    , m_cube()
    , m_localTransform(FTransform::Identity)
{}

///////////////////////////////////////////////////////////////////////////////
UCubePrimitive& UCubeComponent::GetCube(void) { return m_cube; }

///////////////////////////////////////////////////////////////////////////////
const UCubePrimitive& UCubeComponent::GetCube(void) const { return m_cube; }

///////////////////////////////////////////////////////////////////////////////
const FTransform& UCubeComponent::GetLocalTransform(void) const
{
    return m_localTransform;
}

///////////////////////////////////////////////////////////////////////////////
void UCubeComponent::SetLocalTransform(const FTransform& transform)
{
    m_localTransform = transform;
}

///////////////////////////////////////////////////////////////////////////////
void UCubeComponent::Render(IRenderer& renderer) const
{
    if (IsHiddenInGame()) { return; }

    // Update the cube transform with owner + local transform
    FTransform ownerTransform = GetOwner()->GetTransform();
    m_cube.SetTransform(ownerTransform * m_localTransform);

    FRenderStates states;
    m_cube.Draw(renderer, states);
}

}   // namespace tkd
