///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Assets/UResourceHandle.hpp>
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Primitives/UBillboardPrimitive.hpp>
#include <Engine/Runtime/Animations/UFlipBook.hpp>
#include <Engine/Runtime/Components/UActorComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief A component that represents a 3D billboard primitive in the game
/// world
///
/// Billboards are textured quads that always face the camera, useful for
/// sprites in 3D space, particles, and UI elements in the game world.
///
///////////////////////////////////////////////////////////////////////////////
class UBillboardComponent : public UActorComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UActorComponent;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Display mode enumeration
    ///
    ///////////////////////////////////////////////////////////////////////////
    enum class EDisplayMode
    {
        StaticTexture,   //<! Display a static texture
        FlipBook         //<! Display an animated flipbook
    };

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    mutable UBillboardPrimitive m_billboard;   //<! The billboard primitive
    FTransform m_localTransform;      //<! The local transform of the billboard
    FilePath m_texturePath;           //<! Path to the texture file
    FTextureHandle m_textureHandle;   //<! Handle to the loaded texture
    EDisplayMode m_displayMode;       //<! Current display mode
    UFlipBook* m_flipBook;            //<! FlipBook for animated billboards

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ////////////////////////////////////////////////////////////////////////////
    UBillboardComponent(const FString& name = "BillboardComponent");

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the billboard primitive associated with this component
    ///
    /// \return Reference to the billboard
    ///
    ///////////////////////////////////////////////////////////////////////////
    UBillboardPrimitive& GetBillboard(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the billboard primitive associated with this component
    ///
    /// \return Constant reference to the billboard
    ///
    ///////////////////////////////////////////////////////////////////////////
    const UBillboardPrimitive& GetBillboard(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the local transform of the billboard
    ///
    /// \return Constant reference to the local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FTransform& GetLocalTransform(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the local transform of the billboard
    ///
    /// \param transform The new local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetLocalTransform(const FTransform& transform);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the texture path for the billboard
    ///
    /// \return The file path to the texture
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FilePath& GetTexturePath(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the texture path for the billboard
    ///
    /// \param texturePath The file path to the texture
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetTexturePath(const FilePath& texturePath);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the billboard using the provided renderer
    ///
    /// \param renderer The renderer to use for drawing
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current display mode
    ///
    /// \return The current display mode
    ///
    ///////////////////////////////////////////////////////////////////////////
    EDisplayMode GetDisplayMode(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the display mode
    ///
    /// \param mode The display mode to set
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetDisplayMode(EDisplayMode mode);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the FlipBook for animated billboards
    ///
    /// \param flipBook Pointer to the FlipBook to use
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetFlipBook(UFlipBook* flipBook);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current FlipBook
    ///
    /// \return Pointer to the current FlipBook (nullptr if none)
    ///
    ///////////////////////////////////////////////////////////////////////////
    UFlipBook* GetFlipBook(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Update the component (for FlipBook animation)
    ///
    /// \param deltaTime Time elapsed since last update
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Tick(Float32 deltaTime) override;
};

}   // namespace tkd
