///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Object/UObject.hpp>
#include <Engine/Runtime/Time/ITickable.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief
///
///////////////////////////////////////////////////////////////////////////////
class UActorComponent
    : public UObject
    , public ITickable
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FString m_name;    //<! Name of the component
    Bool m_isActive;   //<! Whether the component is active

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ///////////////////////////////////////////////////////////////////////////
    UActorComponent(const FString& name);

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the active state of the component
    ///
    /// \param isActive The new active state
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetActive(Bool isActive);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the active state of the component
    ///
    /// \return True if the component is active, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    Bool IsActive(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the name of the component
    ///
    /// \return The name of the component
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FString& GetName(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is first created
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void BeginPlay(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Ticks the object
    ///
    /// \param deltaTime The time elapsed since the last tick
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Tick(Float32 deltaTime) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is being destroyed
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void EndPlay(void) override;
};

}   // namespace tkd
