///////////////////////////class UWidgetComponent : public
/// UActorComponent/////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Interfaces/IRenderer.hpp>
#include <Engine/Runtime/Components/UActorComponent.hpp>
#include <Engine/Runtime/Input/FInputManager.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Base component class for UI widgets
///
/// Provides core functionality for widget components. Derived classes should
/// implement specific widget behavior and rendering.
///
///////////////////////////////////////////////////////////////////////////////
class UWidgetComponent : public UActorComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UActorComponent;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Alignment options for widget positioning
    ///
    ///////////////////////////////////////////////////////////////////////////
    enum class EAlignment
    {
        None,           ///< No alignment, use exact position
        TopLeft,        ///< Align to top left corner
        TopCenter,      ///< Align to top center
        TopRight,       ///< Align to top right corner
        CenterLeft,     ///< Align to center left
        Center,         ///< Align to center (default)
        CenterRight,    ///< Align to center right
        BottomLeft,     ///< Align to bottom left corner
        BottomCenter,   ///< Align to bottom center
        BottomRight     ///< Align to bottom right corner
    };

protected:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FInputManager* m_inputManager;   //<! The input manager
    FVector2 m_position;             ///< Widget position in screen space
    FVector2 m_rawPosition;          ///< Raw position (no alignment applied)
    FVector2 m_size;                 ///< Widget dimensions (width, height)
    FVector2 m_rawSize;              ///< Widget dimensions (width, height)
    FVector2 m_scale;                ///< Widget scale factor
    Int32 m_zIndex;          ///< Layer ordering (higher numbers appear on top)
    EAlignment m_align;      ///< Widget alignment
    bool m_visible;          ///< Visibility state
    bool m_enabled;          ///< Interaction state
    bool m_rawModeEnabled;   ///< If true, use raw position and scale

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ////////////////////////////////////////////////////////////////////////////
    UWidgetComponent(const FString& name = "WidgetComponent");

    ///////////////////////////////////////////////////////////////////////////
    // Non-copyable
    ///////////////////////////////////////////////////////////////////////////
    UWidgetComponent(const UWidgetComponent&) = delete;
    UWidgetComponent& operator=(const UWidgetComponent&) = delete;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current position of the widget
    ///
    /// \return The current position in screen coordinates
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FVector2& GetPosition(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the position of the widget in screen space
    ///
    /// \param position The new position in screen coordinates
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetPosition(const FVector2& position);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the raw position (no alignment applied)
    ///
    /// \return The raw position in screen coordinates
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FVector2& GetRawPosition(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the raw position (no alignment applied)
    ///
    /// \param position The new raw position in screen coordinates
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetRawPosition(const FVector2& position);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the raw mode state
    ///
    /// \return True if raw mode is active, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool GetRawMode(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the raw mode state
    ///
    /// \param enabled True to enable raw mode, false to disable it
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetRawMode(bool enabled);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the widget is currently visible
    ///
    /// \return True if the widget is visible, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool IsVisible(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the visibility of the widget
    ///
    /// \param visible True to show the widget, false to hide it
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetVisible(Bool visible);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the size of the widget
    ///
    /// \return The current size (width, height)
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FVector2& GetSize(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the size of the widget
    ///
    /// \param size The new size (width, height)
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetSize(const FVector2& size);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the rawsize of the widget
    ///
    /// \return The current raw size (width, height)
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FVector2& GetRawSize(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the raw size of the widget
    ///
    /// \param size The new raw size (width, height)
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetRawSize(const FVector2& size);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the scale of the widget
    ///
    /// \return The current scale factor
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FVector2& GetScale(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the scale of the widget
    ///
    /// \param scale The new scale factor
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetScale(const FVector2& scale);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the Z-index of the widget
    ///
    /// \return The current Z-index
    ///
    ///////////////////////////////////////////////////////////////////////////
    Int32 GetZIndex(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the Z-index of the widget
    ///
    /// \param zIndex The new Z-index
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetZIndex(Int32 zIndex);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the alignment of the widget
    ///
    /// \return The current alignment
    ///
    ///////////////////////////////////////////////////////////////////////////
    EAlignment GetAlignment(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the alignment of the widget
    ///
    /// \param alignment The new alignment
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetAlignment(EAlignment alignment);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Calculate origin offset based on current alignment setting
    ///
    /// \return The origin offset vector
    ///
    ///////////////////////////////////////////////////////////////////////////
    FVector2 GetOrigin() const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the widget is enabled
    ///
    /// \return True if the widget is enabled, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool IsEnabled(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the enabled state of the widget
    ///
    /// \param enabled True to enable the widget, false to disable it
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetEnabled(Bool enabled);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the input manager for the inputs
    ///
    /// \param inputManager the input manager to set
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetInputManager(FInputManager* inputManager);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is first created
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void BeginPlay(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is being destroyed
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void EndPlay(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Update the widget's state
    ///
    /// \param deltaTime Time elapsed since last update
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Tick(Float32 deltaTime) override;
};

}   // namespace tkd
