///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Runtime/Components/UPlaneComponent.hpp>
#include <Engine/Runtime/Actor/AActor.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
UPlaneComponent::UPlaneComponent(const FString& name)
    : UActorComponent(name)
    , m_plane()
    , m_localTransform(FTransform::Identity)
{}

///////////////////////////////////////////////////////////////////////////////
UPlanePrimitive& UPlaneComponent::GetPlane(void) { return m_plane; }

///////////////////////////////////////////////////////////////////////////////
const UPlanePrimitive& UPlaneComponent::GetPlane(void) const
{
    return m_plane;
}

///////////////////////////////////////////////////////////////////////////////
const FTransform& UPlaneComponent::GetLocalTransform(void) const
{
    return m_localTransform;
}

///////////////////////////////////////////////////////////////////////////////
void UPlaneComponent::SetLocalTransform(const FTransform& transform)
{
    m_localTransform = transform;
}

///////////////////////////////////////////////////////////////////////////////
void UPlaneComponent::Render(IRenderer& renderer) const
{
    if (IsHiddenInGame()) { return; }

    // Update the plane transform with owner + local transform
    FTransform ownerTransform = GetOwner()->GetTransform();
    m_plane.SetTransform(ownerTransform * m_localTransform);

    FRenderStates states;
    m_plane.Draw(renderer, states);
}

}   // namespace tkd
