///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Primitives/UConePrimitive.hpp>
#include <Engine/Runtime/Components/UActorComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief A component that represents a 3D cone primitive in the game world
///
///////////////////////////////////////////////////////////////////////////////
class UConeComponent : public UActorComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UActorComponent;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    mutable UConePrimitive m_cone;   //<! The cone primitive
    FTransform m_localTransform;     //<! The local transform of the cone

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ////////////////////////////////////////////////////////////////////////////
    UConeComponent(const FString& name = "ConeComponent");

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the cone primitive associated with this component
    ///
    /// \return Reference to the cone
    ///
    ///////////////////////////////////////////////////////////////////////////
    UConePrimitive& GetCone(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the cone primitive associated with this component
    ///
    /// \return Constant reference to the cone
    ///
    ///////////////////////////////////////////////////////////////////////////
    const UConePrimitive& GetCone(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the local transform of the cone
    ///
    /// \return Constant reference to the local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FTransform& GetLocalTransform(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the local transform of the cone
    ///
    /// \param transform The new local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetLocalTransform(const FTransform& transform);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the cone using the provided renderer
    ///
    /// \param renderer The renderer to use for drawing
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;
};

}   // namespace tkd
