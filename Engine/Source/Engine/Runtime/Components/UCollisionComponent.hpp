#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Core/Object/UObject.hpp>
#include <Engine/Runtime/Components/UActorComponent.hpp>
#include <Engine/Runtime/Physics/FAABB.hpp>
#include <Engine/Runtime/Physics/FOBB.hpp>
#include <Engine/Runtime/Physics/UPhysicsObject.hpp>
#include <vector>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
// Forward declarations
///////////////////////////////////////////////////////////////////////////////
class UCollisionSystem;

///////////////////////////////////////////////////////////////////////////////
/// \brief Generic collision component class
///
///////////////////////////////////////////////////////////////////////////////
class UCollisionComponent
    : public UActorComponent
    , public UPhysicsObject
{
protected:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    UCollisionSystem*
        m_collisionSystem;   //<! Reference to the collision system
    bool m_showDebug;        //<! Whether to show debug info

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    UCollisionComponent(const FString& name = "CollisionComponent");

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the local bounding box of the component
    ///
    /// \return The local oriented bounding box
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FOBB GetLocalBoundingBox(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the world bounding box of the component
    ///
    /// \return The world oriented bounding box
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FOBB GetWorldBoundingBox(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the world AABB for spatial partitioning
    ///
    /// \return The world axis-aligned bounding box
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FAABB GetWorldAABB(void) const = 0;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the collision system
    ///
    /// \param system Pointer to the collision system
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetCollisionSystem(UCollisionSystem* system);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the collision system
    ///
    /// \return Pointer to the collision system
    ///
    ///////////////////////////////////////////////////////////////////////////
    UCollisionSystem* GetCollisionSystem(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is first created
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void BeginPlay(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is being destroyed
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void EndPlay(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set whether to show debug info
    ///
    /// \param debug Whether to show debug info
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetShowDebug(bool debug);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the cube using the provided renderer
    ///
    /// \param renderer The renderer to use for drawing
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;
};

}   // namespace tkd
