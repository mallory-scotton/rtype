///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Runtime/Components/UConeComponent.hpp>
#include <Engine/Runtime/Actor/AActor.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
UConeComponent::UConeComponent(const FString& name)
    : UActorComponent(name)
    , m_cone()
    , m_localTransform(FTransform::Identity)
{}

///////////////////////////////////////////////////////////////////////////////
UConePrimitive& UConeComponent::GetCone(void) { return m_cone; }

///////////////////////////////////////////////////////////////////////////////
const UConePrimitive& UConeComponent::GetCone(void) const { return m_cone; }

///////////////////////////////////////////////////////////////////////////////
const FTransform& UConeComponent::GetLocalTransform(void) const
{
    return m_localTransform;
}

///////////////////////////////////////////////////////////////////////////////
void UConeComponent::SetLocalTransform(const FTransform& transform)
{
    m_localTransform = transform;
}

///////////////////////////////////////////////////////////////////////////////
void UConeComponent::Render(IRenderer& renderer) const
{
    if (IsHiddenInGame()) { return; }

    // Update the cone transform with owner + local transform
    FTransform ownerTransform = GetOwner()->GetTransform();
    m_cone.SetTransform(ownerTransform * m_localTransform);

    FRenderStates states;
    m_cone.Draw(renderer, states);
}

}   // namespace tkd
