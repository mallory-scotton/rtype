///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Primitives/USpherePrimitive.hpp>
#include <Engine/Runtime/Components/UActorComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief A component that represents a 3D sphere primitive in the game world
///
///////////////////////////////////////////////////////////////////////////////
class USphereComponent : public UActorComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UActorComponent;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    mutable USpherePrimitive m_sphere;   //<! The sphere primitive
    FTransform m_localTransform;         //<! The local transform of the sphere

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ////////////////////////////////////////////////////////////////////////////
    USphereComponent(const FString& name = "SphereComponent");

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the sphere primitive associated with this component
    ///
    /// \return Reference to the sphere
    ///
    ///////////////////////////////////////////////////////////////////////////
    USpherePrimitive& GetSphere(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the sphere primitive associated with this component
    ///
    /// \return Constant reference to the sphere
    ///
    ///////////////////////////////////////////////////////////////////////////
    const USpherePrimitive& GetSphere(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the local transform of the sphere
    ///
    /// \return Constant reference to the local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FTransform& GetLocalTransform(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the local transform of the sphere
    ///
    /// \param transform The new local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetLocalTransform(const FTransform& transform);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the sphere using the provided renderer
    ///
    /// \param renderer The renderer to use for drawing
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;
};

}   // namespace tkd
