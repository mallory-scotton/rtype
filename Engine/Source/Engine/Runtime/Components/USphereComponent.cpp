///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Runtime/Components/USphereComponent.hpp>
#include <Engine/Runtime/Actor/AActor.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
USphereComponent::USphereComponent(const FString& name)
    : UActorComponent(name)
    , m_sphere()
    , m_localTransform(FTransform::Identity)
{}

///////////////////////////////////////////////////////////////////////////////
USpherePrimitive& USphereComponent::GetSphere(void) { return m_sphere; }

///////////////////////////////////////////////////////////////////////////////
const USpherePrimitive& USphereComponent::GetSphere(void) const
{
    return m_sphere;
}

///////////////////////////////////////////////////////////////////////////////
const FTransform& USphereComponent::GetLocalTransform(void) const
{
    return m_localTransform;
}

///////////////////////////////////////////////////////////////////////////////
void USphereComponent::SetLocalTransform(const FTransform& transform)
{
    m_localTransform = transform;
}

///////////////////////////////////////////////////////////////////////////////
void USphereComponent::Render(IRenderer& renderer) const
{
    if (IsHiddenInGame()) { return; }

    // Update the sphere transform with owner + local transform
    FTransform ownerTransform = GetOwner()->GetTransform();
    m_sphere.SetTransform(ownerTransform * m_localTransform);

    FRenderStates states;
    m_sphere.Draw(renderer, states);
}

}   // namespace tkd
