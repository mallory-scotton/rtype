///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Primitives/UChamferCubePrimitive.hpp>
#include <Engine/Runtime/Components/UActorComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief A component that represents a 3D chamfer cube primitive in the game
/// world
///
/// The chamfer cube component wraps a chamfer cube primitive and provides
/// integration with the actor/component system. It supports texture mapping,
/// local transforms, and parametizable chamfer size for beveled edges.
///
///////////////////////////////////////////////////////////////////////////////
class UChamferCubeComponent : public UActorComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UActorComponent;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Members
    ///////////////////////////////////////////////////////////////////////////
    mutable UChamferCubePrimitive m_chamferCube;   //<! The chamfer cube
                                                   // primitive
    FTransform m_localTransform;   //<! The local transform of the chamfer cube

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    /// \param chamferSize Size of the chamfer (0.0 to 0.5, default 0.1)
    ///
    ////////////////////////////////////////////////////////////////////////////
    UChamferCubeComponent(
        const FString& name = "ChamferCubeComponent",
        Float32 chamferSize = 0.1f
    );

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the chamfer cube primitive associated with this component
    ///
    /// \return Reference to the chamfer cube
    ///
    ///////////////////////////////////////////////////////////////////////////
    UChamferCubePrimitive& GetChamferCube(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the chamfer cube primitive associated with this component
    ///
    /// \return Constant reference to the chamfer cube
    ///
    ///////////////////////////////////////////////////////////////////////////
    const UChamferCubePrimitive& GetChamferCube(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the local transform of the chamfer cube
    ///
    /// \return Constant reference to the local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FTransform& GetLocalTransform(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the local transform of the chamfer cube
    ///
    /// \param transform The new local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetLocalTransform(const FTransform& transform);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the texture of the chamfer cube
    ///
    /// \param texture The texture to apply to the chamfer cube
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetTexture(ITexture* texture);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the texture of the chamfer cube
    ///
    /// \return Pointer to the texture
    ///
    ///////////////////////////////////////////////////////////////////////////
    ITexture* GetTexture(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the chamfer size
    ///
    /// \param size New chamfer size (0.0 to 0.5)
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetChamferSize(Float32 size);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the chamfer size
    ///
    /// \return Current chamfer size
    ///
    ///////////////////////////////////////////////////////////////////////////
    Float32 GetChamferSize(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the chamfer cube using the provided renderer
    ///
    /// \param renderer The renderer to use for drawing
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Render(IRenderer& renderer) const override;
};

}   // namespace tkd
