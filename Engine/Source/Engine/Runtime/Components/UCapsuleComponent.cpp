///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Runtime/Components/UCapsuleComponent.hpp>
#include <Engine/Runtime/Actor/AActor.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
UCapsuleComponent::UCapsuleComponent(const FString& name)
    : UActorComponent(name)
    , m_capsule()
    , m_localTransform(FTransform::Identity)
{}

///////////////////////////////////////////////////////////////////////////////
UCapsulePrimitive& UCapsuleComponent::GetCapsule(void) { return m_capsule; }

///////////////////////////////////////////////////////////////////////////////
const UCapsulePrimitive& UCapsuleComponent::GetCapsule(void) const
{
    return m_capsule;
}

///////////////////////////////////////////////////////////////////////////////
const FTransform& UCapsuleComponent::GetLocalTransform(void) const
{
    return m_localTransform;
}

///////////////////////////////////////////////////////////////////////////////
void UCapsuleComponent::SetLocalTransform(const FTransform& transform)
{
    m_localTransform = transform;
}

///////////////////////////////////////////////////////////////////////////////
void UCapsuleComponent::Render(IRenderer& renderer) const
{
    if (IsHiddenInGame()) { return; }

    // Update the capsule transform with owner + local transform
    FTransform ownerTransform = GetOwner()->GetTransform();
    m_capsule.SetTransform(ownerTransform * m_localTransform);

    FRenderStates states;
    m_capsule.Draw(renderer, states);
}

}   // namespace tkd
