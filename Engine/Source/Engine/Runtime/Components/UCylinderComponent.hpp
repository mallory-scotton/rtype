///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Primitives/UCylinderPrimitive.hpp>
#include <Engine/Runtime/Components/UActorComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief A component that represents a 3D cylinder primitive in the game
/// world
///
///////////////////////////////////////////////////////////////////////////////
class UCylinderComponent : public UActorComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UActorComponent;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    mutable UCylinderPrimitive m_cylinder;   //<! The cylinder primitive
    FTransform m_localTransform;   //<! The local transform of the cylinder

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ////////////////////////////////////////////////////////////////////////////
    UCylinderComponent(const FString& name = "CylinderComponent");

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the cylinder primitive associated with this component
    ///
    /// \return Reference to the cylinder
    ///
    ///////////////////////////////////////////////////////////////////////////
    UCylinderPrimitive& GetCylinder(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the cylinder primitive associated with this component
    ///
    /// \return Constant reference to the cylinder
    ///
    ///////////////////////////////////////////////////////////////////////////
    const UCylinderPrimitive& GetCylinder(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the local transform of the cylinder
    ///
    /// \return Constant reference to the local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FTransform& GetLocalTransform(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the local transform of the cylinder
    ///
    /// \param transform The new local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetLocalTransform(const FTransform& transform);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the cylinder using the provided renderer
    ///
    /// \param renderer The renderer to use for drawing
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;
};

}   // namespace tkd
