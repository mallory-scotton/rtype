///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Interfaces/IRenderer.hpp>
#include <Engine/Renderer/Shapes/URectangleShape.hpp>
#include <Engine/Runtime/Components/UWidgetComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Clickbox widget component that responds to mouse input
///         with a rectangle background activable for debug purposes
///
///////////////////////////////////////////////////////////////////////////////
class UWidgetButtonComponent : public UWidgetComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UWidgetComponent;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FColor m_color;                     ///< Button background color
    URectangleShape m_rectangleShape;   ///< Rectangle shape for rendering
    int m_clicks;                       ///< Number of clicks on the widget

public:
    ///////////////////////////////////////////////////////////////////////////
    // Callback function types
    ///////////////////////////////////////////////////////////////////////////
    using FOnClickCallback = std::function<void()>;
    using FOnUnclickedCallback = std::function<void()>;
    using FOnReleasedCallback = std::function<void()>;
    using FOnHeldCallback = std::function<void()>;
    using FOnHoverCallback = std::function<void()>;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Callback Members
    ///////////////////////////////////////////////////////////////////////////
    FOnClickCallback m_onClickCallback;           ///< when button is clicked
    FOnUnclickedCallback m_onUnclickedCallback;   ///< when button is unclicked
    FOnReleasedCallback m_onReleasedCallback;     ///< when button is released
    FOnHeldCallback m_onHeldCallback;             ///< while button is held
    FOnHoverCallback m_onHoverCallback;           ///< when button is hovered

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ////////////////////////////////////////////////////////////////////////////
    UWidgetButtonComponent(const FString& name = "WidgetButtonComponent");

    ///////////////////////////////////////////////////////////////////////////
    // Non-copyable
    ///////////////////////////////////////////////////////////////////////////
    UWidgetButtonComponent(const UWidgetButtonComponent&) = delete;
    UWidgetButtonComponent& operator=(const UWidgetButtonComponent&) = delete;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the callback for when button is clicked
    ///
    /// \param callback Function to call on click
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetOnClick(FOnClickCallback callback);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the callback for when button is unclicked (released after
    /// click)
    ///
    /// \param callback Function to call on unclick
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetOnUnclicked(FOnUnclickedCallback callback);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the callback for when button is released
    ///
    /// \param callback Function to call on release
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetOnReleased(FOnReleasedCallback callback);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the callback for while button is held
    ///
    /// \param callback Function to call while held
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetOnHeld(FOnHeldCallback callback);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the callback for when button is hovered
    ///
    /// \param callback Function to call on hover
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetOnHover(FOnHoverCallback callback);

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current color of the Button
    ///
    /// \return The current color
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FColor& GetColor(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the color of the Button
    ///
    /// \param color The new color
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetColor(const FColor& color);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Render the Button (draw rectangle)
    ///
    /// \param renderer The renderer to draw with
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Per-frame update
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Tick(Float32 deltaTime) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is first created
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void BeginPlay(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is being destroyed
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void EndPlay(void) override;
};

}   // namespace tkd
