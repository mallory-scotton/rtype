///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Interfaces/IRenderer.hpp>
#include <Engine/Renderer/Shapes/URectangleShape.hpp>
#include <Engine/Renderer/Shapes/UTextShape.hpp>
#include <Engine/Runtime/Components/UWidgetComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Textbox widget component for text input
///         with a rectangle background and editable text
///
///////////////////////////////////////////////////////////////////////////////
class UWidgetTextComponent : public UWidgetComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UWidgetComponent;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FColor m_color;           ///< Text color
    FString m_text;           ///< Current text content
    FVector2 m_charSize;      ///< Character size
    Float32 m_spacing;        ///< Spacing between characters
    FVector2 m_origin;
    UTextShape m_textShape;   ///< Text shape for displaying text
    FilePath m_fontPath;      ///< Path to the font file
    bool m_isFocused;         ///< Whether the textbox is focused

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ////////////////////////////////////////////////////////////////////////////
    UWidgetTextComponent(const FString& name = "WidgetTextComponent");

    ///////////////////////////////////////////////////////////////////////////
    // Non-copyable
    ///////////////////////////////////////////////////////////////////////////
    UWidgetTextComponent(const UWidgetTextComponent&) = delete;
    UWidgetTextComponent& operator=(const UWidgetTextComponent&) = delete;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current background color
    ///
    /// \return The current color
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FColor& GetColor(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the background color
    ///
    /// \param color The new color
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetColor(const FColor& color);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current text content
    ///
    /// \return The current text
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FString& GetText(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the text content
    ///
    /// \param text The new text
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetText(const FString& text);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the font path
    ///
    /// \param path Path to the font file
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetFontPath(const FilePath& path);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the font path
    ///
    /// \return The font path
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FilePath& GetFontPath(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the character size
    ///
    /// \param size The new character size
    ///
    ////////////////////////////////////////////////////////////////////////////
    void SetCharacterSize(const FVector2 size);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the character size
    ///
    /// \return The current character size
    ///
    ////////////////////////////////////////////////////////////////////////////
    const FVector2 GetCharacterSize(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the spacing between characters
    ///
    /// \param spacing The new spacing value
    ///
    ////////////////////////////////////////////////////////////////////////////
    void SetSpacing(const Float32 spacing);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the spacing between characters
    ///
    /// \return The current spacing value
    ///
    ////////////////////////////////////////////////////////////////////////////
    Float32 GetSpacing(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Render the textbox (background + text)
    ///
    /// \param renderer The renderer to draw with
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Per-frame update
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Tick(Float32 deltaTime) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is first created
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void BeginPlay(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is being destroyed
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void EndPlay(void) override;
};

}   // namespace tkd
