///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Interfaces/IRenderer.hpp>
#include <Engine/Renderer/Shapes/URectangleShape.hpp>
#include <Engine/Renderer/Shapes/UTextShape.hpp>
#include <Engine/Runtime/Components/UWidgetComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Textbox widget component for text input
///         with a rectangle background and editable text
///
///////////////////////////////////////////////////////////////////////////////
class UWidgetTextboxComponent : public UWidgetComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UWidgetComponent;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FColor m_backgroundColor;           ///< Background color (normal)
    FColor m_focusedBackgroundColor;    ///< Background color when focused
    FColor m_textColor;                 ///< Text color
    URectangleShape m_rectangleShape;   ///< Rectangle shape for background
    UTextShape m_textShape;             ///< Text shape for displaying text

    FString m_text;                     ///< Current text content
    FString m_typedText;                ///< Text being typed
    FilePath m_fontPath;                ///< Path to the font file
    FVector2 m_charSize;                ///< Character size
    Float32 m_spacing;                  ///< Spacing between characters

    UInt32 m_maxCharacters;             ///< Maximum characters (0 = unlimited)
    UInt32 m_minBoxChars;               ///< min size for box (in characters)
    UInt32 m_maxBoxChars;               ///< max size for box (in characters)
    bool m_adaptSizeToText;             ///< Whether box adapts to text size

    std::unordered_map<EInput, float> m_keyCooldowns;   ///< Key cooldowns

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ////////////////////////////////////////////////////////////////////////////
    UWidgetTextboxComponent(const FString& name = "WidgetTextboxComponent");

    ///////////////////////////////////////////////////////////////////////////
    // Non-copyable
    ///////////////////////////////////////////////////////////////////////////
    UWidgetTextboxComponent(const UWidgetTextboxComponent&) = delete;
    UWidgetTextboxComponent&
        operator=(const UWidgetTextboxComponent&) = delete;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the background color (when not focused)
    ///
    /// \param color The new background color
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetBackgroundColor(const FColor& color);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the background color
    ///
    /// \return The current background color
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FColor& GetBackgroundColor(void) const { return m_backgroundColor; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the focused background color
    ///
    /// \param color The new focused background color
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetFocusedBackgroundColor(const FColor& color);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the focused background color
    ///
    /// \return The focused background color
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FColor& GetFocusedBackgroundColor(void) const
    {
        return m_focusedBackgroundColor;
    }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the text color
    ///
    /// \param color The new text color
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetTextColor(const FColor& color);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the text color
    ///
    /// \return The current text color
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FColor& GetTextColor(void) const { return m_textColor; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current text content
    ///
    /// \return The current text
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FString& GetText(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the text content
    ///
    /// \param text The new text
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetText(const FString& text);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the font path
    ///
    /// \param path Path to the font file
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetFontPath(const FilePath& path);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the font path
    ///
    /// \return The font path
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FilePath& GetFontPath(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the character size
    ///
    /// \param size The new character size
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetCharacterSize(const FVector2& size);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the character size
    ///
    /// \return The current character size
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FVector2& GetCharacterSize(void) const { return m_charSize; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the spacing between characters
    ///
    /// \param spacing The new spacing value
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetSpacing(Float32 spacing);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the spacing between characters
    ///
    /// \return The current spacing value
    ///
    ///////////////////////////////////////////////////////////////////////////
    Float32 GetSpacing(void) const { return m_spacing; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if a point is inside the textbox bounds
    ///
    /// \param point The point to test in screen coordinates
    ///
    /// \return True if the point is inside, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool ContainsPoint(const FVector2& point) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Render the textbox (background + text)
    ///
    /// \param renderer The renderer to draw with
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Capture typed text input when focused
    ///
    ///////////////////////////////////////////////////////////////////////////
    void CaptureTypedText(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Erase text from the cursor position to the beginning of the word
    ///
    /// \param text The text to modify
    ///
    ///////////////////////////////////////////////////////////////////////////
    void EraseCtrlBackspace(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the maximum number of characters allowed
    ///
    /// \param maxChars Maximum characters (0 = unlimited)
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetMaxCharacters(UInt32 maxChars);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the maximum number of characters
    ///
    /// \return Maximum characters (0 = unlimited)
    ///
    ///////////////////////////////////////////////////////////////////////////
    UInt32 GetMaxCharacters(void) const { return m_maxCharacters; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set minimum visible characters (box won't shrink below this)
    ///
    /// \param minChars Minimum visible characters
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetMinBoxChars(UInt32 minChars);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get minimum visible characters
    ///
    /// \return Minimum visible characters
    ///
    ///////////////////////////////////////////////////////////////////////////
    UInt32 GetMinBoxChars(void) const { return m_minBoxChars; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set maximum visible characters (box won't grow beyond this)
    ///
    /// \param maxChars Maximum visible characters
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetMaxBoxChars(UInt32 maxChars);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get maximum visible characters
    ///
    /// \return Maximum visible characters
    ///
    ///////////////////////////////////////////////////////////////////////////
    UInt32 GetMaxBoxChars(void) const { return m_maxBoxChars; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set whether box adapts to text size
    ///
    /// \param adapt True to adapt size, false for fixed size
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetAdaptSizeToText(bool adapt);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get whether box adapts to text size
    ///
    /// \return True if adapting, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool GetAdaptSizeToText(void) const { return m_adaptSizeToText; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is first created
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void BeginPlay(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is being destroyed
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void EndPlay(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Per-frame update
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Tick(Float32 deltaTime) override;
};

}   // namespace tkd
