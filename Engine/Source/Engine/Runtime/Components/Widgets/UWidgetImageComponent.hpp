///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Renderer/Interfaces/IRenderer.hpp>
#include <Engine/Renderer/USprite.hpp>
#include <Engine/Runtime/Components/UWidgetComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

class UWidgetImageComponent : public UWidgetComponent
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class metadata
    ///////////////////////////////////////////////////////////////////////////
    using Super = UWidgetComponent;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    USprite m_sprite;                 ///< Sprite for rendering the image
    FTextureHandle m_textureHandle;   ///< Handle to the loaded texture
    FilePath m_texturePath;           ///< Path to the texture file
    FColor m_color;                   ///< Color of the Sprite

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param name The name of the component
    ///
    ////////////////////////////////////////////////////////////////////////////
    UWidgetImageComponent(const FString& name = "WidgetImageComponent");

    ///////////////////////////////////////////////////////////////////////////
    // Non-copyable
    ///////////////////////////////////////////////////////////////////////////
    UWidgetImageComponent(const UWidgetImageComponent&) = delete;
    UWidgetImageComponent& operator=(const UWidgetImageComponent&) = delete;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the texture path
    ///
    /// \param path The path to the texture file
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetTexturePath(const FilePath& path);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the texture path
    ///
    /// \return The path to the texture file
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FilePath& GetTexturePath() const { return m_texturePath; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the sprite associated with this component
    ///
    /// \return Reference to the sprite
    ///
    ///////////////////////////////////////////////////////////////////////////
    USprite& GetSprite() { return m_sprite; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the sprite associated with this component
    ///
    /// \return Constant reference to the sprite
    ///
    ///////////////////////////////////////////////////////////////////////////
    const USprite& GetSprite() const { return m_sprite; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is first created
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void BeginPlay(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the Sprite Color (0-1)
    ///
    /// \param color The Color the sprite should have (tint)
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetColor(const FColor& color);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the Sprite Color (0-255)
    ///
    /// \param color The Color the sprite should have (tint)
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetColor(const FLinearColor& color);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the sprite's Color (white is default)
    ///
    /// \return Color
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FColor& GetColor() const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is being destroyed
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void EndPlay(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Per-frame update
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Tick(Float32 deltaTime) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Render the Button (draw rectangle)
    ///
    /// \param renderer The renderer to draw with
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const override;
};

}   // namespace tkd
