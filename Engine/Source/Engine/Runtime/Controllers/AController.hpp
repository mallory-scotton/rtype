///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core.hpp>
#include <Engine/Runtime/Actor/APawn.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
// Forward declarations
///////////////////////////////////////////////////////////////////////////////
class AController;

///////////////////////////////////////////////////////////////////////////////
/// \brief Event types for AController
///
///////////////////////////////////////////////////////////////////////////////
template <>
class TEvents<AController>
{
public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Event data for the Possess event
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct Possess
    {
        APawn* pawn;   //<! The pawn that was possessed.
    };

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Event data for the UnPossess event
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct UnPossess
    {
        APawn* pawn;   //<! The pawn that was unpossessed.
    };

public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    using All = std::tuple<Possess, UnPossess>;
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Base class for all controllers
///
///////////////////////////////////////////////////////////////////////////////
class AController
    : public UObject
    , public TEventEmitter<TEvents<AController>::All>
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Aliases
    ///////////////////////////////////////////////////////////////////////////
    using Events = TEvents<AController>;

protected:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    APawn* m_pawn;   //<! The pawn that this controller is controlling.

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    AController(void) = default;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Virtual destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~AController() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Possess a pawn
    ///
    /// \param pawn The pawn to possess
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Possess(APawn* pawn);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Unpossess the currently possessed pawn
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void UnPossess(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the currently possessed pawn
    ///
    /// \return The currently possessed pawn, or nullptr if none
    ///
    ///////////////////////////////////////////////////////////////////////////
    APawn* GetPawn(void) const;
};

}   // namespace tkd
