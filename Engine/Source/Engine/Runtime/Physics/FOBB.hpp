namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Oriented Bounding Box (OBB) class
///
///////////////////////////////////////////////////////////////////////////////
class FOBB
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FVector3 center;    //<! Center of the OBB
    FVector3 extents;   //<! Half-extents along each local axis
    FVector3 axes[3];   //<! Local axes (normalized)

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    FOBB(void);

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Update from transform
    ///
    /// \param transform The world transform
    /// \param halfExtents The half-extents of the box
    ///
    ///////////////////////////////////////////////////////////////////////////
    void UpdateFromTransform(
        const FTransform& transform, const FVector3& halfExtents
    );

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get corners of the OBB
    ///
    /// \param corners Output array of 8 corners
    ///
    ///////////////////////////////////////////////////////////////////////////
    void GetCorners(FVector3 corners[8]) const;
};

}   // namespace tkd
