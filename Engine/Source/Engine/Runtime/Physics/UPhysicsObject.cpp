///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Runtime/Physics/UPhysicsObject.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
UPhysicsObject::UPhysicsObject(
    EPhysicsBodyType bodyType,
    ECollisionDetection collisionMode,
    ECollisionResponse collisionResponse,
    ECollisionChannel collisionChannel
)
    : m_bodyType(bodyType)
    , m_collisionMode(collisionMode)
    , m_collisionResponse(collisionResponse)
    , m_collisionChannel(collisionChannel)
{}

///////////////////////////////////////////////////////////////////////////////
void UPhysicsObject::SetBodyType(EPhysicsBodyType bodyType)
{
    m_bodyType = bodyType;
}

///////////////////////////////////////////////////////////////////////////////
void UPhysicsObject::SetCollisionMode(ECollisionDetection collisionMode)
{
    m_collisionMode = collisionMode;
}

///////////////////////////////////////////////////////////////////////////////
void UPhysicsObject::SetCollisionResponse(ECollisionResponse collisionResponse)
{
    m_collisionResponse = collisionResponse;
}

///////////////////////////////////////////////////////////////////////////////
void UPhysicsObject::SetCollisionChannel(ECollisionChannel collisionChannel)
{
    m_collisionChannel = collisionChannel;
}

///////////////////////////////////////////////////////////////////////////////
EPhysicsBodyType UPhysicsObject::GetBodyType(void) const { return m_bodyType; }

///////////////////////////////////////////////////////////////////////////////
ECollisionDetection UPhysicsObject::GetCollisionMode(void) const
{
    return m_collisionMode;
}

///////////////////////////////////////////////////////////////////////////////
ECollisionResponse UPhysicsObject::GetCollisionResponse(void) const
{
    return m_collisionResponse;
}

///////////////////////////////////////////////////////////////////////////////
ECollisionChannel UPhysicsObject::GetCollisionChannel(void) const
{
    return m_collisionChannel;
}

}   // namespace tkd
