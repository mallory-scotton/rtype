///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Runtime/Physics/FAABB.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
FAABB::FAABB(void)
    : min(FVector3::Zero)
    , max(FVector3::Zero)
{}

///////////////////////////////////////////////////////////////////////////////
FAABB::FAABB(const FVector3& minimum, const FVector3& maximum)
    : min(minimum)
    , max(maximum)
{}

///////////////////////////////////////////////////////////////////////////////
bool FAABB::Intersects(const FAABB& other) const
{
    return (min.x <= other.max.x && max.x >= other.min.x) &&
           (min.y <= other.max.y && max.y >= other.min.y) &&
           (min.z <= other.max.z && max.z >= other.min.z);
}

///////////////////////////////////////////////////////////////////////////////
FVector3 FAABB::GetCenter(void) const
{
    return FVector3(
        (min.x + max.x) * 0.5f, (min.y + max.y) * 0.5f, (min.z + max.z) * 0.5f
    );
}

///////////////////////////////////////////////////////////////////////////////
FVector3 FAABB::GetExtents(void) const
{
    return FVector3(
        (max.x - min.x) * 0.5f, (max.y - min.y) * 0.5f, (max.z - min.z) * 0.5f
    );
}

}   // namespace tkd
