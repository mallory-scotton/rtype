#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Core/Object.hpp>
#include <Engine/Runtime/Physics/Enumerations.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Physics Object class to encapsulate physics properties
///
///////////////////////////////////////////////////////////////////////////////
class UPhysicsObject
{
protected:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    EPhysicsBodyType m_bodyType;              //<! The physics body type
    ECollisionDetection m_collisionMode;      //<! The collision detection mode
    ECollisionResponse m_collisionResponse;   //<! The collision response type
    ECollisionChannel m_collisionChannel;     //<! The collision channel

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor
    ///
    /// \param bodyType The physics body type
    /// \param collisionMode The collision detection mode
    /// \param collisionResponse The collision response type
    /// \param collisionChannel The collision channel
    ///
    ///////////////////////////////////////////////////////////////////////////
    UPhysicsObject(
        EPhysicsBodyType bodyType = EPhysicsBodyType::Static,
        ECollisionDetection collisionMode = ECollisionDetection::Discrete,
        ECollisionResponse collisionResponse = ECollisionResponse::Block,
        ECollisionChannel collisionChannel = ECollisionChannel::PhysicsBody
    );

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~UPhysicsObject() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the physics body type
    ///
    /// \param bodyType The new physics body type
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetBodyType(EPhysicsBodyType bodyType);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the collision detection mode
    ///
    /// \param collisionMode The new collision detection mode
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetCollisionMode(ECollisionDetection collisionMode);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the collision response type
    ///
    /// \param collisionResponse The new collision response type
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetCollisionResponse(ECollisionResponse collisionResponse);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the collision channel
    ///
    /// \param collisionChannel The new collision channel
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetCollisionChannel(ECollisionChannel collisionChannel);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the physics body type
    ///
    /// \return The physics body type
    ///
    ///////////////////////////////////////////////////////////////////////////
    EPhysicsBodyType GetBodyType(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the collision detection mode
    ///
    /// \return The collision detection mode
    ///
    ///////////////////////////////////////////////////////////////////////////
    ECollisionDetection GetCollisionMode(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the collision response type
    ///
    /// \return The collision response type
    ///
    ///////////////////////////////////////////////////////////////////////////
    ECollisionResponse GetCollisionResponse(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the collision channel
    ///
    /// \return The collision channel
    ///
    ///////////////////////////////////////////////////////////////////////////
    ECollisionChannel GetCollisionChannel(void) const;
};

}   // namespace tkd
