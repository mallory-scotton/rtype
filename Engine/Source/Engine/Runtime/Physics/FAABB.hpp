///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Axis-Aligned Bounding Box (AABB) structure
///
///////////////////////////////////////////////////////////////////////////////
class FAABB
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FVector3 min;   //<! Minimum corner of the AABB
    FVector3 max;   //<! Maximum corner of the AABB

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor. Initializes the AABB to zero size.
    ///
    ///////////////////////////////////////////////////////////////////////////
    FAABB(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor with specified minimum and maximum corners.
    ///
    /// \param minimum The minimum corner of the AABB
    /// \param maximum The maximum corner of the AABB
    ///
    ///////////////////////////////////////////////////////////////////////////
    FAABB(const FVector3& minimum, const FVector3& maximum);

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if this AABB intersects with another AABB
    ///
    /// \param other The other AABB to check intersection with
    ///
    /// \return True if the AABBs intersect, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool Intersects(const FAABB& other) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the center point of the AABB
    ///
    /// \return The center point of the AABB
    ///
    ///////////////////////////////////////////////////////////////////////////
    FVector3 GetCenter(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the extent (size) of the AABB
    ///
    /// \return The extent of the AABB
    ///
    ///////////////////////////////////////////////////////////////////////////
    FVector3 GetExtents(void) const;
};

}   // namespace tkd
