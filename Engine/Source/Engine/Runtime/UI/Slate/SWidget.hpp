///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core/Math.hpp>
#include <Engine/Runtime/Actor/AHUD.hpp>
#include <Engine/Runtime/Components/USpriteComponent.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Base class for Slate widgets in the UI system
///
/// This widget can be attached to an AHUD and supports sprite rendering.
/// It provides basic positioning, visibility, and sprite management.
///
///////////////////////////////////////////////////////////////////////////////
class SWidget
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Constructor / Destructor
    ///////////////////////////////////////////////////////////////////////////
    explicit SWidget(AHUD* ownerHUD = nullptr);
    virtual ~SWidget() = default;

    ///////////////////////////////////////////////////////////////////////////
    // Non-copyable
    ///////////////////////////////////////////////////////////////////////////
    SWidget(const SWidget&) = delete;
    SWidget& operator=(const SWidget&) = delete;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the sprite component associated with this widget
    ///
    /// \return Reference to the sprite component
    ///
    ///////////////////////////////////////////////////////////////////////////
    USpriteComponent& GetSpriteComponent() { return m_spriteComponent; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the sprite component associated with this widget (const)
    ///
    /// \return Const reference to the sprite component
    ///
    ///////////////////////////////////////////////////////////////////////////
    const USpriteComponent& GetSpriteComponent() const
    {
        return m_spriteComponent;
    }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the position of the widget in screen space
    ///
    /// \param position The new position in screen coordinates
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetPosition(const FVector2& position);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current position of the widget
    ///
    /// \return The current position in screen coordinates
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FVector2& GetPosition() const { return m_position; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the visibility of the widget
    ///
    /// \param visible True to show the widget, false to hide it
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetVisible(bool visible) { m_visible = visible; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the widget is currently visible
    ///
    /// \return True if the widget is visible, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool IsVisible() const { return m_visible; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the owner HUD of this widget
    ///
    /// \return Pointer to the owner HUD
    ///
    ///////////////////////////////////////////////////////////////////////////
    AHUD* GetOwnerHUD() const { return m_ownerHUD; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the owner HUD of this widget
    ///
    /// \param hud Pointer to the HUD that owns this widget
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetOwnerHUD(AHUD* hud) { m_ownerHUD = hud; }

protected:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the widget is added to a HUD
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void OnAddedToHUD() {}

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the widget is removed from a HUD
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void OnRemovedFromHUD() {}

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Update the widget's state
    ///
    /// \param deltaTime Time elapsed since last update
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Tick(Float32 deltaTime);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Render the widget
    ///
    /// \param renderer The renderer to use
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Paint(IRenderer& renderer) const;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class members
    ///////////////////////////////////////////////////////////////////////////
    AHUD* m_ownerHUD;                     //!< The HUD that owns this widget
    USpriteComponent m_spriteComponent;   //!< Sprite component for rendering
    FVector2 m_position;                  //!< Position in screen space
    bool m_visible;                       //!< Visibility flag
};

}   // namespace tkd
