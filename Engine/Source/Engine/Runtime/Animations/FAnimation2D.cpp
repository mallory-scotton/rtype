///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Runtime/Animations/FAnimation2D.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
FAnimation2D::FAnimation2D(const FString& name, bool isLooping)
    : m_name(name)
    , m_isLooping(isLooping)
{}

///////////////////////////////////////////////////////////////////////////////
const FAnimation2DFrame& FAnimation2D::operator[](SizeT index) const
{
    return m_frames[index];
}

///////////////////////////////////////////////////////////////////////////////
void FAnimation2D::AddFrame(const FAnimation2DFrame& frame)
{
    m_frames.PushBack(frame);
}

///////////////////////////////////////////////////////////////////////////////
void FAnimation2D::AddFrame(const FRectanglei& rect, Float32 duration)
{
    m_frames.PushBack(FAnimation2DFrame(rect, duration));
}

///////////////////////////////////////////////////////////////////////////////
SizeT FAnimation2D::GetFrameCount(void) const { return m_frames.Size(); }

///////////////////////////////////////////////////////////////////////////////
const FAnimation2DFrame& FAnimation2D::GetFrame(SizeT index) const
{
    return m_frames[index];
}

///////////////////////////////////////////////////////////////////////////////
const FString& FAnimation2D::GetName(void) const { return m_name; }

///////////////////////////////////////////////////////////////////////////////
bool FAnimation2D::IsLooping(void) const { return m_isLooping; }

///////////////////////////////////////////////////////////////////////////////
void FAnimation2D::SetLooping(bool isLooping) { m_isLooping = isLooping; }

///////////////////////////////////////////////////////////////////////////////
Float32 FAnimation2D::GetTotalDuration(void) const
{
    Float32 totalDuration = 0.0f;
    for (SizeT i = 0; i < m_frames.Size(); ++i)
    {
        totalDuration += m_frames[i].duration;
    }
    return totalDuration;
}

}   // namespace tkd
