namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Class representing a single frame in a 2D animation.
///
///////////////////////////////////////////////////////////////////////////////
class FAnimation2DFrame
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    Float32 duration;          //<! Duration of the frame in seconds
    FRectanglei textureRect;   //<! Texture rectangle for this frame

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor. Initializes duration to 0 and textureRect
    /// to zero rectangle.
    ///
    /// \param rect The texture rectangle
    /// \param duration The duration of the frame in seconds
    ///
    ///////////////////////////////////////////////////////////////////////////
    FAnimation2DFrame(
        const FRectanglei& rect = FRectanglei::Zero, Float32 duration = 0.0f
    )
        : duration(duration)
        , textureRect(rect)
    {}
};

}   // namespace tkd
