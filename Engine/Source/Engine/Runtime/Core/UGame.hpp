#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine/Config.hpp>
#include <Engine/Core.hpp>
#include <Engine/Runtime/Time/ITickable.hpp>
#include <memory>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Base class for a game application
///
///////////////////////////////////////////////////////////////////////////////
class UGame
    : public UObject
    , public ITickable
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    FString m_defaultLevel;       //<! The default level to load
    FEngineSettings m_settings;   //<! The engine settings

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    /// \param settings The engine settings to use
    ///
    ///////////////////////////////////////////////////////////////////////////
    UGame(const FEngineSettings& settings);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Virtual destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~UGame() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Set the default level to load on game start
    ///
    /// \param levelName The name of the level to load
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetDefaultLevel(const FString& levelName);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the engine settings
    ///
    /// \return  The engine settings
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FEngineSettings& GetEngineSettings(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is first created
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void BeginPlay(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Ticks the object
    ///
    /// \param deltaTime The time elapsed since the last tick
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Tick(Float32 deltaTime) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is being destroyed
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void EndPlay(void) override;
};

}   // namespace tkd
