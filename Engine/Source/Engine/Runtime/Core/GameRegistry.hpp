///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Game Registry class
///
///////////////////////////////////////////////////////////////////////////////
class GameRegistry : public TSingleton<GameRegistry>
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Aliases
    ///////////////////////////////////////////////////////////////////////////
    using CreateFunc = TUniquePtr<UGame> (*)(void);

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    CreateFunc m_createFunc;   //<! Function to create a UGame instance

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    GameRegistry(void) = default;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Virtual destructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual ~GameRegistry() = default;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Register a game creation function
    ///
    /// \param func The function to register
    ///
    ///////////////////////////////////////////////////////////////////////////
    static void Register(CreateFunc func);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Create a UGame instance using the registered function
    ///
    /// \return A unique pointer to the created UGame instance
    ///
    ///////////////////////////////////////////////////////////////////////////
    static TUniquePtr<UGame> CreateGameInstance(void);
};

}   // namespace tkd

///////////////////////////////////////////////////////////////////////////////
/// \brief Macro to export a game class
///
///////////////////////////////////////////////////////////////////////////////
#define TKD_EXPORT_GAME(GameClass) \
    extern "C" TKD_API_EXPORT void TKD_EnsureGameLibraryLoaded(void) {} \
    namespace \
    { \
        struct GameRegistrar { \
            GameRegistrar() { \
                tkd::GameRegistry::Register([]() -> std::unique_ptr<tkd::UGame> { \
                    return std::make_unique<GameClass>(); \
                }); \
            } \
        } g_gameRegistrar; \
    }
