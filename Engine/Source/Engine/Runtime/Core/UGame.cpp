namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
UGame::UGame(const FEngineSettings& settings)
    : UObject("UGame")
    , m_defaultLevel("L_DefaultLevel")
    , m_settings(settings)
{}

///////////////////////////////////////////////////////////////////////////////
void UGame::SetDefaultLevel(const FString& levelName)
{
    m_defaultLevel = levelName;
}

///////////////////////////////////////////////////////////////////////////////
const FString& UGame::GetDefaultLevel(void) const { return m_defaultLevel; }

///////////////////////////////////////////////////////////////////////////////
void UGame::AddPackedResource(const FilePath& resource)
{
    m_packedResources.PushBack(resource);
}

///////////////////////////////////////////////////////////////////////////////
const TVector<FilePath>& UGame::GetPackedResources(void) const
{
    return m_packedResources;
}

///////////////////////////////////////////////////////////////////////////////
const FEngineSettings& UGame::GetEngineSettings(void) { return m_settings; }

///////////////////////////////////////////////////////////////////////////////
void UGame::BeginPlay(void) {}

///////////////////////////////////////////////////////////////////////////////
void UGame::Tick(Float32) {}

///////////////////////////////////////////////////////////////////////////////
void UGame::EndPlay(void) {}

}   // namespace tkd
