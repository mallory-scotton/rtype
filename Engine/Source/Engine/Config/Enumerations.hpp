///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Engine VR capability enumeration
///
///////////////////////////////////////////////////////////////////////////////
enum class EVRCapability
{
    Disabled,   //<! VR support disabled
    Optional,   //<! VR support optional
    Required    //<! VR support required
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Engine VR device enumeration
///
///////////////////////////////////////////////////////////////////////////////
enum class EVRDevice
{
    None,       //<! No VR device
    OpenVR,     //<! OpenVR compatible device
    Oculus,     //<! Oculus VR device
    Vive,       //<! HTC Vive device
    Index,      //<! Valve Index device
    WindowsMR   //<! Windows Mixed Reality device
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Engine VR movement mode enumeration
///
///////////////////////////////////////////////////////////////////////////////
enum class EVRMovementMode
{
    Teleportation,     //<! Teleportation movement
    SmoothLocomotion   //<! Smooth locomotion movement
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Engine VR snap turn angle enumeration
///
///////////////////////////////////////////////////////////////////////////////
enum class EVRSnapTurnAngle
{
    None,      //<! No snap turn
    Angle45,   //<! 45 degree snap turn
    Angle90    //<! 90 degree snap turn
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Engine network capability enumeration
///
///////////////////////////////////////////////////////////////////////////////
enum class ENetworkCapability
{
    Disabled,   //<! Networking disabled
    Optional,   //<! Networking optional
    Required    //<! Networking required
};

}   // namespace tkd
