#include <Engine/Config.hpp>
#include <Engine/Core/Containers/FString.hpp>
#include <memory>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Smart handle for resource management with reference counting
///
/// \tparam T The type of resource (ITexture, IShader, etc.)
///
///////////////////////////////////////////////////////////////////////////////
template <typename T>
class TResourceHandle
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Members
    ///////////////////////////////////////////////////////////////////////////
    std::shared_ptr<T> m_resource;   //<! Shared pointer to the resource
    FString m_id;                    //<! Unique identifier for the resource

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    TResourceHandle(void)
        : m_resource(nullptr)
        , m_id("")
    {}

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor with resource and id
    ///
    /// \param resource Shared pointer to the resource
    /// \param id Unique identifier for the resource
    ///
    ///////////////////////////////////////////////////////////////////////////
    TResourceHandle(std::shared_ptr<T> resource, const FString& id)
        : m_resource(resource)
        , m_id(id)
    {}

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the raw pointer to the resource
    ///
    /// \return Raw pointer to the resource, or nullptr if not valid
    ///
    ///////////////////////////////////////////////////////////////////////////
    T* Get(void) const { return m_resource.get(); }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the resource ID
    ///
    /// \return The unique identifier for this resource
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FString& GetId(void) const { return m_id; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Check if the handle is valid
    ///
    /// \return True if the handle points to a valid resource
    ///
    ///////////////////////////////////////////////////////////////////////////
    bool IsValid(void) const { return m_resource != nullptr; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get reference count
    ///
    /// \return Number of references to this resource
    ///
    ///////////////////////////////////////////////////////////////////////////
    SizeT GetRefCount(void) const
    {
        return m_resource ? m_resource.use_count() : 0;
    }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Reset the handle
    ///
    ///////////////////////////////////////////////////////////////////////////
    void Reset(void)
    {
        m_resource.reset();
        m_id = "";
    }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Arrow operator for direct access to resource
    ///
    /// \return Raw pointer to the resource
    ///
    ///////////////////////////////////////////////////////////////////////////
    T* operator->(void) const { return m_resource.get(); }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Dereference operator
    ///
    /// \return Reference to the resource
    ///
    ///////////////////////////////////////////////////////////////////////////
    T& operator*(void) const { return *m_resource; }

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Bool conversion operator
    ///
    /// \return True if the handle is valid
    ///
    ///////////////////////////////////////////////////////////////////////////
    explicit operator bool(void) const { return IsValid(); }
};

///////////////////////////////////////////////////////////////////////////////
// Type aliases for common resource handles
///////////////////////////////////////////////////////////////////////////////
class ITexture;
class IShader;
class IAudioSource;
class IAudioBuffer;

using FTextureHandle = TResourceHandle<ITexture>;
using FShaderHandle = TResourceHandle<IShader>;
using FAudioSourceHandle = TResourceHandle<IAudioSource>;
using FAudioBufferHandle = TResourceHandle<IAudioBuffer>;

}   // namespace tkd
