namespace tkd::__internal
{

///////////////////////////////////////////////////////////////////////////////
/// \brief
///
///////////////////////////////////////////////////////////////////////////////
class World
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Static Members
    ///////////////////////////////////////////////////////////////////////////
    static std::vector<std::unique_ptr<UWorld>> s_worlds;
    static std::unique_ptr<UWorld> s_currentWorld;

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the current world
    ///
    /// \return The current world or nullptr if no world is loaded
    ///
    ///////////////////////////////////////////////////////////////////////////
    static UWorld* Get(void);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Spawn a new actor in the world
    ///
    /// \tparam Actor The type of actor to spawn
    ///
    /// \param actorClass The class of the actor to spawn
    /// \param spawnTransform The transform to spawn the actor at
    ///
    /// \return True if the actor was successfully spawned, false otherwise
    ///
    ///////////////////////////////////////////////////////////////////////////
    template <typename Actor>
    Bool SpawnActor(const FTransform& spawnTransform)
    {
        static_assert(
            std::is_base_of<AActor, Actor>::value,
            "Actor must be a subclass of AActor"
        );
        if (s_currentWorld)
        {
            s_currentWorld->SpawnActor<Actor>(spawnTransform);
            return true;
        }
        return false;
    }
};

}   // namespace tkd::__internal
