    static UThread s_networkThread;         //<! Network thread of the engine
#if TKD_ENGINE_CLIENT
    static UThread s_renderThread;          //<! Render thread of the engine
#endif

public:
    ///////////////////////////////////////////////////////////////////////////
    // Public types
    ///////////////////////////////////////////////////////////////////////////
