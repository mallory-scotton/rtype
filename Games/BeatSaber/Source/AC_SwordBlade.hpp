///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Sword Blade Actor Component
///
///////////////////////////////////////////////////////////////////////////////
class AC_SwordBlade : public UCollisionComponent
{
private:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Structure to hold a point in the sword trail
    ///
    ///////////////////////////////////////////////////////////////////////////
    struct TrailPoint
    {
        FVector3 tipPosition;    //<! Position of the blade tip
        FVector3 basePosition;   //<! Position of the blade base
        float lifetime;          //<! Time since the point was created
    };

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Aliases
    ///////////////////////////////////////////////////////////////////////////
    using Super = UCollisionComponent;

private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    VR::EHand m_hand;   //<! The hand this sword blade is associated with
    VR::FControllerState m_state;   //<! The current state of the controller
    mutable std::vector<TrailPoint>
        m_trailPoints;              //<! Points for the sword trail
    SizeT m_trailMaxPoints;         //<! Maximum points in the sword trail
    float m_trailMinVelocity;       //<! Minimum velocity to show trail

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Constructor
    ///
    /// \param name The name of the component
    /// \param hand The hand this sword blade is associated with
    ///
    ///////////////////////////////////////////////////////////////////////////
    AC_SwordBlade(
        const FString& name = "SwordBlade", VR::EHand hand = VR::EHand::Left
    );

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the local bounding box of the component
    ///
    /// \return The local oriented bounding box
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FOBB GetLocalBoundingBox(void) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the world bounding box of the component
    ///
    /// \return The world oriented bounding box
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FOBB GetWorldBoundingBox(void) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Get the world AABB for spatial partitioning
    ///
    /// \return The world axis-aligned bounding box
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual FAABB GetWorldAABB(void) const override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is first created
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void BeginPlay(void) override;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Renders the component
    ///
    /// \param renderer The renderer to use for rendering
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Called when the object is updated each frame
    ///
    /// \param deltaTime The time elapsed since the last tick
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Tick(float deltaTime) override;

private:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw a cylinder for the sword blade
    ///
    /// \param radius The radius of the cylinder
    /// \param height The height of the cylinder
    /// \param segments The number of segments around the cylinder
    ///
    ///////////////////////////////////////////////////////////////////////////
    void DrawCylinder(float radius, float height, int segments = 16) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw a sphere for glow effects
    ///
    /// \param radius The radius of the sphere
    /// \param slices The number of slices (longitude divisions)
    /// \param stacks The number of stacks (latitude divisions)
    ///
    ///////////////////////////////////////////////////////////////////////////
    void DrawSphere(float radius, int slices, int stacks) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Update the sword trail points
    ///
    /// \param deltaTime The time elapsed since the last update
    ///
    ///////////////////////////////////////////////////////////////////////////
    void UpdateTrail(float deltaTime);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Draw the sword trail
    ///
    ///////////////////////////////////////////////////////////////////////////
    void DrawTrail(void) const;
};

}   // namespace tkd
