///////////////////////////////////////////////////////////////////////////////
#include <Engine.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief
///
///////////////////////////////////////////////////////////////////////////////
class AC_HollowCube : public UActorComponent
{
private:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    float m_outerScale;            //<! Scale of the outer cube
    float m_innerScale;            //<! Scale of the inner cube
    float m_thickness;             //<! Thickness of the cube walls
    FColor m_color;                //<! Color of the hollow cube
    FTransform m_localTransform;   //<! Local transform for positioning

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default constructor
    ///
    ///////////////////////////////////////////////////////////////////////////
    AC_HollowCube(const FString& name = "AC_HollowCube");

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the outer scale of the hollow cube
    ///
    /// \param scale The new outer scale
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetOuterScale(float scale);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the inner scale of the hollow cube
    ///
    /// \param scale The new inner scale
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetInnerScale(float scale);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the thickness of the cube walls
    ///
    /// \param thickness The new wall thickness
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetThickness(float thickness);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the color of the hollow cube
    ///
    /// \param color The new color
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetColor(const FColor& color);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Sets the local transform of the hollow cube
    ///
    /// \param transform The new local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    void SetLocalTransform(const FTransform& transform);

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Gets the local transform of the hollow cube
    ///
    /// \return The current local transform
    ///
    ///////////////////////////////////////////////////////////////////////////
    const FTransform& GetLocalTransform(void) const;

    ///////////////////////////////////////////////////////////////////////////
    /// \brief Renders the component
    ///
    /// \param renderer The renderer to use for rendering
    ///
    ///////////////////////////////////////////////////////////////////////////
    virtual void Render(IRenderer& renderer) const;
};

}   // namespace tkd

