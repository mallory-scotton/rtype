///////////////////////////////////////////////////////////////////////////////
// Header guard
///////////////////////////////////////////////////////////////////////////////
#pragma once

///////////////////////////////////////////////////////////////////////////////
// Dependencies
///////////////////////////////////////////////////////////////////////////////
#include <Engine.hpp>

///////////////////////////////////////////////////////////////////////////////
// Namespace tkd
///////////////////////////////////////////////////////////////////////////////
namespace tkd
{

///////////////////////////////////////////////////////////////////////////////
/// \brief Enumeration for the Beat Saber game states
///
///////////////////////////////////////////////////////////////////////////////
enum class EBeatSaberGameState
{
    None,      //<! No state
    Menu,      //<! In the main menu
    Playing,   //<! Playing a level
    Paused     //<! Game is paused
};

///////////////////////////////////////////////////////////////////////////////
/// \brief Singleton class to hold global state information
///
///////////////////////////////////////////////////////////////////////////////
class ST_State : public TSingleton<ST_State>
{
public:
    ///////////////////////////////////////////////////////////////////////////
    // Class Member
    ///////////////////////////////////////////////////////////////////////////
    EBeatSaberGameState gameState =
        EBeatSaberGameState::None;    //<! Current game state
    Float32 beatTime{ 0.0f };         //<! Current beat time
    Float32 playTime{ 0.0f };         //<! Current play time in seconds
    TSharedPtr<IAudioSource> music;   //<! The music source

public:
    ///////////////////////////////////////////////////////////////////////////
    /// \brief Default Constructor for ST_State
    ///
    ///////////////////////////////////////////////////////////////////////////
    ST_State(void) = default;
};

}   // namespace tkd

